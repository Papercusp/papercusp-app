-- 292-benchmark-hive-layer.sql
--
-- impartial-benchmark-suite-2026-06-15 Phase 5 (D-010) — the HIVE reframe: the
-- suite now benchmarks the Queen+fleet over a whole BACKLOG, with the per-task
-- run_result (migration 291) as the L1 atomic unit the fleet places. This adds
-- the L2 reproducibility records (BRIEF 8 / P-010 EXTEND), mirroring the locked
-- @papercusp/bench-metrics fleet contracts (P-011 / P-025+P-026):
--
--   benchmark_fleet_run — one arm's run over a backlog (mirrors FleetRunSummary +
--     repro extras). arm ∈ FleetArmId (hive | queen-ablated | native-serial |
--     competitor; OPEN union → no CHECK). The hive − queen-ablated delta IS the
--     Queen's measured value (the NEW HEADLINE baseline). Read by P-011's
--     throughputMetrics / valueMetrics / buildHiveReport.
--
--   benchmark_coord_event — the raw fleet/coordination trace (mirrors CoordEvent):
--     normal actions (spawn/handoff/claim/complete/…) the MAST judge reads + the
--     mechanical failure signals (duplicate_completion / orphaned_claim /
--     stranded_item / claim_conflict / superseded_work / rework) that
--     substrateSignalRates counts objectively → P-026 MAST duplication /
--     breakdown / misalignment rates. `kind` is OPEN text (CoordEventKind union).
--
-- Plus a soft `fleet_run_id` link on benchmark_run_result so an L1 task row is
-- attributable to the L2 fleet run that placed it (NO FK — L1 rows are emitted
-- DURING the run, before the fleet_run summary lands; the id is deterministic so
-- the runner stamps it upfront).
--
-- Idempotent (CREATE/ALTER ... IF NOT EXISTS); additive; fresh-migrate-safe. RLS
-- + grants mirror migration 291 / experiment_runs (287).

-- ─── L1 link: attribute a per-task row to its fleet run ──────────────────────
ALTER TABLE harness_shared.benchmark_run_result
  ADD COLUMN IF NOT EXISTS fleet_run_id text;

CREATE INDEX IF NOT EXISTS benchmark_run_result_fleet_run_idx
  ON harness_shared.benchmark_run_result (workspace_id, fleet_run_id);

-- ─── L2: one arm's run over a whole backlog (mirrors FleetRunSummary) ────────
CREATE TABLE IF NOT EXISTS harness_shared.benchmark_fleet_run (
    -- = sha256(run_id ∥ suite ∥ backlog_id ∥ arm ∥ seed). Deterministic → idempotent.
    fleet_run_id         text NOT NULL PRIMARY KEY,
    run_id               text NOT NULL,
    workspace_id         text NOT NULL,
    -- Every fleet run runs under a pre-registered config (firewall, enforced in emit).
    prereg_hash          text NOT NULL,
    suite                text NOT NULL,
    -- FleetArmId — OPEN union (competitors slot in); no CHECK.
    arm                  text NOT NULL,
    -- The task SET handed to the arm.
    backlog_id           text NOT NULL,
    -- Independent attempt of the whole-backlog run.
    seed                 integer NOT NULL,
    -- ── FleetRunSummary core ──
    tasks                integer NOT NULL,
    resolved             integer NOT NULL,
    -- autonomy numerator: tasks completed with ZERO human gate.
    tasks_zero_human_gate integer NOT NULL DEFAULT 0,
    -- wall-clock to drain the whole backlog.
    wall_clock_ms        bigint NOT NULL,
    -- total tokens + $ across the WHOLE fleet (coordination overhead counted).
    tokens_total         bigint NOT NULL,
    cost_usd             double precision NOT NULL,
    price_table_version  text NOT NULL,
    peak_concurrency     integer,
    -- ── L3 value-capture (optional; P-025 valueMetrics) ──
    value_captured_usd   double precision,
    value_available_usd  double precision,
    budget_usd           double precision,
    -- iso-budget cap for the whole run (null = uncapped).
    budget_tokens        bigint,
    -- ── provenance ──
    model_id             text NOT NULL,
    harness_version      text NOT NULL,
    config_snapshot      jsonb,
    env_fingerprint      jsonb,
    arm_meta             jsonb,
    created_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, run_id, backlog_id, arm, seed)
);

CREATE INDEX IF NOT EXISTS benchmark_fleet_run_ws_run_idx
  ON harness_shared.benchmark_fleet_run (workspace_id, run_id);

-- ─── L2: the coordination trace (mirrors CoordEvent; MAST-convertible) ───────
CREATE TABLE IF NOT EXISTS harness_shared.benchmark_coord_event (
    event_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_run_id   text NOT NULL,
    run_id         text NOT NULL,
    workspace_id   text NOT NULL,
    -- ordering within the fleet run (insertion order; the trace is replayed in seq).
    seq            bigint NOT NULL,
    -- CoordEvent.ts — ms epoch or relative (ordering only; nullable).
    ts             bigint,
    -- CoordEventKind — OPEN text (spawn|handoff|claim|complete|… + the mechanical
    -- failure signals duplicate_completion|orphaned_claim|stranded_item|
    -- claim_conflict|superseded_work|rework that substrateSignalRates counts).
    kind           text NOT NULL,
    -- acting agent / bee id.
    agent          text,
    -- the benchmark task this event relates to, if any.
    task_id        text,
    detail         text,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS benchmark_coord_event_run_seq_idx
  ON harness_shared.benchmark_coord_event (workspace_id, fleet_run_id, seq);

-- ─── Workspace isolation (RLS) + runtime-role grants (mirror migration 291) ──
ALTER TABLE harness_shared.benchmark_fleet_run   ENABLE ROW LEVEL SECURITY;
ALTER TABLE harness_shared.benchmark_coord_event ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS benchmark_fleet_run_workspace_isolation ON harness_shared.benchmark_fleet_run;
CREATE POLICY benchmark_fleet_run_workspace_isolation ON harness_shared.benchmark_fleet_run
    USING ((workspace_id = current_setting('app.workspace_id'::text, true)))
    WITH CHECK ((workspace_id = current_setting('app.workspace_id'::text, true)));

DROP POLICY IF EXISTS benchmark_coord_event_workspace_isolation ON harness_shared.benchmark_coord_event;
CREATE POLICY benchmark_coord_event_workspace_isolation ON harness_shared.benchmark_coord_event
    USING ((workspace_id = current_setting('app.workspace_id'::text, true)))
    WITH CHECK ((workspace_id = current_setting('app.workspace_id'::text, true)));

GRANT SELECT, INSERT, UPDATE, DELETE ON harness_shared.benchmark_fleet_run   TO harness_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON harness_shared.benchmark_coord_event TO harness_app;
GRANT SELECT ON harness_shared.benchmark_fleet_run   TO harness_zero;
GRANT SELECT ON harness_shared.benchmark_coord_event TO harness_zero;
