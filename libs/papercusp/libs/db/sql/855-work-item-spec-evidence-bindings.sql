CREATE TRIGGER spec_evidence_bindings_immutable
  BEFORE UPDATE OR DELETE ON harness_shared.spec_evidence_bindings
  FOR EACH ROW EXECUTE FUNCTION harness_shared.reject_spec_evidence_history_mutation();

