-- 253-calibration-predictions.sql
--
-- self-learning-frontier-2026-06-12 (P-041 / FB-13): calibration markets —
-- cheap recorded claims ("bets") captured at natural moments (improvement
-- resolve calls, plan starts, flake filings), resolved later against observed
-- outcomes, and Brier-scored per persona per domain. The scores feed (a) the
-- one queue ranker (P-040 / FB-12, D-005 — calibration is a FEATURE, never a
-- ranker) and (b) Queen-weighting of agent claims via calibration:summary.
--
-- One row per bet. A bet is OPEN (resolved_at IS NULL) until the resolution
-- sweep (system:calibration-resolve) matures it against its domain probe:
--   outcome boolean  — the claim's truth at resolution; NULL with resolved_at
--                      set = VOIDED (probe undeterminable past grace) — voided
--                      rows never enter Brier scoring.
--   stated           — true when the predictor explicitly stated probability;
--                      false for the implicit per-domain prior (seams record
--                      cheaply with no blocking UX — the brief's rule).
--   signal_origin    — frontier D-002 provenance vocabulary; consumers filter
--                      to organic unless explicitly opted in.
--   watchdog_key     — the filed signal's stable identity, for the
--                      flake-recurrence probe's re-capture lookup.
--
-- Domain + subject_kind vocabularies OWNED by packages/operator-core/lib/
-- calibration/ (plain text so the seam can evolve).
--
-- Volume: a few rows per resolve/plan-start/flake filing — hundreds per month.
-- No RLS (mirrors 245/252): the sweep, the feature, and the tool scope by
-- workspace_id explicitly.

CREATE TABLE IF NOT EXISTS harness_shared.calibration_predictions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    text NOT NULL,
    predictor       text NOT NULL,
    domain          text NOT NULL,
    subject_kind    text NOT NULL,
    subject_id      text NOT NULL,
    claim           text NOT NULL,
    probability     double precision NOT NULL,
    stated          boolean NOT NULL DEFAULT false,
    signal_origin   text NOT NULL DEFAULT 'organic',
    watchdog_key    text,
    horizon_ts      timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    resolved_at     timestamptz,
    outcome         boolean,
    resolution_note text,
    CONSTRAINT calibration_predictions_ws_nonempty CHECK (workspace_id <> ''),
    CONSTRAINT calibration_predictions_predictor_nonempty CHECK (predictor <> ''),
    CONSTRAINT calibration_predictions_probability_range CHECK (probability >= 0 AND probability <= 1),
    CONSTRAINT calibration_predictions_origin_vocab
      CHECK (signal_origin IN ('organic', 'drill', 'replay', 'shadow')),
    -- A scored outcome implies resolution; resolved with NULL outcome = voided.
    CONSTRAINT calibration_predictions_outcome_resolved
      CHECK (outcome IS NULL OR resolved_at IS NOT NULL)
);

-- One OPEN bet per predictor × domain × subject (re-resolving the same item
-- re-records idempotently — the store inserts ON CONFLICT DO NOTHING).
CREATE UNIQUE INDEX IF NOT EXISTS calibration_predictions_open_bet_uq
  ON harness_shared.calibration_predictions (workspace_id, predictor, domain, subject_kind, subject_id)
  WHERE resolved_at IS NULL;

-- The sweep's matured scan.
CREATE INDEX IF NOT EXISTS calibration_predictions_matured_idx
  ON harness_shared.calibration_predictions (workspace_id, horizon_ts)
  WHERE resolved_at IS NULL;

-- The ranker feature's per-subject lookup.
CREATE INDEX IF NOT EXISTS calibration_predictions_subject_idx
  ON harness_shared.calibration_predictions (workspace_id, subject_kind, subject_id);

-- Per-persona per-domain Brier aggregation.
CREATE INDEX IF NOT EXISTS calibration_predictions_scores_idx
  ON harness_shared.calibration_predictions (workspace_id, predictor, domain);

GRANT SELECT, INSERT, UPDATE ON harness_shared.calibration_predictions TO harness_app;
GRANT USAGE, SELECT ON SEQUENCE harness_shared.calibration_predictions_id_seq TO harness_app;
-- Bets are history: resolution UPDATEs outcome once, nothing deletes (the 246
-- lesson — the baseline's default privileges widen new tables to ALL; revoke
-- the destructive verbs explicitly).
REVOKE DELETE, TRUNCATE ON harness_shared.calibration_predictions FROM harness_app;
DO $z$ BEGIN
  GRANT SELECT ON harness_shared.calibration_predictions TO harness_zero;
  REVOKE UPDATE, DELETE, TRUNCATE ON harness_shared.calibration_predictions FROM harness_zero;
EXCEPTION WHEN undefined_object THEN NULL;
END $z$;
