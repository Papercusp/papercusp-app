-- 846-coverage-census-tables
--
-- The coverage census: the substrate that turns "is this fully tested?" from a judgment call
-- into a computed verdict.
-- Plan: deterministic-coverage-census-2026-08-17 (P-001), decisions D-001..D-003, D-007.
--
-- THE MODEL IN ONE LINE: coverage = census (what surfaces EXIST, derived from code registries)
-- ⋈ evidence (what tests DEMONSTRABLY touched them). Both halves are facts; the join is the
-- verdict; no agent judgment sits anywhere in that path.
--
-- WHY A SURFACE TABLE AND NOT A COVERAGE PERCENTAGE: line coverage answers "which source lines
-- ran", which is a different question from "which consumer-visible behaviours are verified". A
-- middleware-heavy service reads 85% line coverage while 18 of 50 endpoints have zero tests
-- (this is the documented reason the whole swagger-coverage/TraceCov tool family exists). The
-- unit that can be missing is a SURFACE, so the ledger's grain is a surface.
--
-- WHY THE ROWS ARE PROJECTED, NEVER HAND-AUTHORED: a hand-maintained surface list drifts the
-- first time someone forgets to update it, and drift here is SILENT FALSE CONFIDENCE — the worst
-- failure this system can have. Every row is derived by a SurfaceCensusProvider from the same
-- registration code that serves production traffic (routeRegistrationOrder(), the agent-tools
-- index, the sync-resolver registry), so a surface that can serve a request is in the census by
-- construction. That is also why retired_at exists instead of DELETE: history stays queryable.
--
-- EXPAND-ONLY, so no FORWARD-COMPAT acknowledgment is required: this migration only CREATEs new
-- relations. It alters no existing table, drops nothing, and the currently-deployed :3070 release
-- neither reads nor writes any of it. Nothing here can affect a running process.

-- ---------------------------------------------------------------------------------------------
-- testing_surfaces — the census. One row per testable surface, per harness.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS harness_shared.testing_surfaces (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text        NOT NULL,
    harness_slug text        NOT NULL,
    kind         text        NOT NULL,
    surface_id   text        NOT NULL,
    source_file  text,
    schema_ref   jsonb,
    attrs        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    provider     text        NOT NULL,
    fidelity     text        NOT NULL,
    first_seen   timestamptz NOT NULL DEFAULT now(),
    last_seen    timestamptz NOT NULL DEFAULT now(),
    retired_at   timestamptz
);

-- workspace_id/harness_slug are NOT NULL WITHOUT a default, deliberately: this is a brand-new
-- relation with no legacy rows, so every writer is new code that knows its own scope. NOT NULL
-- forces the census job to state the scope; a DEFAULT would let it silently write to the wrong
-- one (lint:no-workspace-default guards exactly that).
COMMENT ON COLUMN harness_shared.testing_surfaces.workspace_id IS
  'Writing workspace. NOT NULL and never defaulted — the census job always knows its scope (lint:no-workspace-default).';
COMMENT ON COLUMN harness_shared.testing_surfaces.kind IS
  'Surface class, matching the SurfaceCensusProvider that produced it: http-route | mcp-tool | sync-query | ui-route-state | agent-role | ts-export. Open-ended by design (a new provider adds a kind, no migration).';
COMMENT ON COLUMN harness_shared.testing_surfaces.surface_id IS
  'Provider-stable identity within (harness, kind): "POST /api/widgets", "widgets:list", "/admin/testing?tab=live". Must be STABLE across census runs — an unstable id retires and re-creates the row every run, resetting first_seen and defeating the new-surface gate.';
COMMENT ON COLUMN harness_shared.testing_surfaces.source_file IS
  'Repo-relative implementing file. This is the REVERSE MAP that makes plan-scoped gating possible: a plan''s work-items record filesChanged, and those files resolve to the surfaces the plan touched.';
COMMENT ON COLUMN harness_shared.testing_surfaces.schema_ref IS
  'The surface''s own schema (zod JSON / OpenAPI fragment) when it has one. This is what the generated L2 tier consumes — the fuzz harness derives arbitraries from it — so census and generator read the SAME source and a new surface is fuzz-covered without anyone writing a file.';
COMMENT ON COLUMN harness_shared.testing_surfaces.fidelity IS
  'HOW this row was derived: declared (from a live code registry — cannot drift) > spec > convention > observed > file-only. Carried into every verdict so a coverage number computed over a weak census can never be read as one computed over a declared census.';
COMMENT ON COLUMN harness_shared.testing_surfaces.first_seen IS
  'When the census first observed this surface. The green-checkpoint NEW-surface guard is scoped by this (first_seen after the last green pin), which is what lets the gate stop new debt without freezing the backlog.';
COMMENT ON COLUMN harness_shared.testing_surfaces.retired_at IS
  'Set when a census run no longer finds the surface. Never DELETE: a retired surface''s evidence stays queryable, and a surface that comes back keeps its original first_seen.';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'testing_surfaces_fidelity_check') THEN
    ALTER TABLE harness_shared.testing_surfaces
      ADD CONSTRAINT testing_surfaces_fidelity_check
      CHECK (fidelity IN ('declared', 'spec', 'convention', 'observed', 'file-only'));
  END IF;
END $$;

-- Identity of a surface. Every column is NOT NULL, so plain UNIQUE is safe here (no NULL-is-
-- distinct trap) and this doubles as the census job's upsert conflict target.
CREATE UNIQUE INDEX IF NOT EXISTS testing_surfaces_identity
  ON harness_shared.testing_surfaces (workspace_id, harness_slug, kind, surface_id);

-- The live census read (every gate, panel and gap query filters retired rows out).
CREATE INDEX IF NOT EXISTS testing_surfaces_live
  ON harness_shared.testing_surfaces (workspace_id, harness_slug, kind)
  WHERE retired_at IS NULL;

-- The reverse map: changed files -> surfaces. Partial because a surface with no known
-- implementing file can never be reached this way.
CREATE INDEX IF NOT EXISTS testing_surfaces_source_file
  ON harness_shared.testing_surfaces (source_file)
  WHERE source_file IS NOT NULL AND retired_at IS NULL;

-- ---------------------------------------------------------------------------------------------
-- coverage_evidence — observed proof that something tested a surface.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS harness_shared.coverage_evidence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surface_ref   bigint      NOT NULL REFERENCES harness_shared.testing_surfaces (id) ON DELETE CASCADE,
    evidence_kind text        NOT NULL,
    verdict       text        NOT NULL,
    generated     boolean     NOT NULL DEFAULT false,
    test_file     text,
    test_case     text,
    test_run_id   bigint      REFERENCES harness_shared.test_runs (id) ON DELETE SET NULL,
    score         real,
    details       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    observed_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN harness_shared.coverage_evidence.evidence_kind IS
  'traffic (the request/tool-call actually happened — ground truth, from the test-mode attribution middleware) | file-coverage (v8 mapped the covered file to this surface — real but weaker) | fuzz (a generated adversarial suite verdict) | crawl (UI render/console/axe verdict) | mutation (a scoped Stryker run).';
COMMENT ON COLUMN harness_shared.coverage_evidence.generated IS
  'TRUE when the test was machine-generated (fuzz harness, crawler). This single flag is what separates the L2 floor from L3 intent: an intent test is by definition one a MACHINE DID NOT WRITE. Without it, a fuzzer would satisfy the very criterion that exists to require human understanding of intended behaviour.';
COMMENT ON COLUMN harness_shared.coverage_evidence.test_case IS
  'The individual case within test_file, when known (the @verifies:<rubric>/<criterion> tag or the test name). NULL = file-level evidence only. Case-level granularity is what stops a fat green file from satisfying a criterion whose specific behaviour case was never written (D-007).';
COMMENT ON COLUMN harness_shared.coverage_evidence.test_run_id IS
  'The run this evidence came from. ON DELETE SET NULL rather than CASCADE: pruning old runs must not silently erase the coverage history that gates read — the evidence stays, it just loses its drill-down.';
COMMENT ON COLUMN harness_shared.coverage_evidence.score IS
  'Numeric verdict where the evidence has one — currently the mutation score (killed/total). NULL for pass/fail-shaped evidence.';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'coverage_evidence_kind_check') THEN
    ALTER TABLE harness_shared.coverage_evidence
      ADD CONSTRAINT coverage_evidence_kind_check
      CHECK (evidence_kind IN ('traffic', 'file-coverage', 'fuzz', 'crawl', 'mutation'));
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'coverage_evidence_verdict_check') THEN
    ALTER TABLE harness_shared.coverage_evidence
      ADD CONSTRAINT coverage_evidence_verdict_check
      CHECK (verdict IN ('pass', 'fail', 'error', 'skip'));
  END IF;
END $$;

-- A mutation row without a score is an unreadable verdict, and a score outside 0..1 is a unit
-- confusion (percent vs fraction) — the exact class of misreading that costs a retraction.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'coverage_evidence_score_check') THEN
    ALTER TABLE harness_shared.coverage_evidence
      ADD CONSTRAINT coverage_evidence_score_check
      CHECK ((evidence_kind <> 'mutation' AND (score IS NULL OR (score >= 0 AND score <= 1)))
          OR (evidence_kind =  'mutation' AND score IS NOT NULL AND score >= 0 AND score <= 1));
  END IF;
END $$;

-- Dedup target for the attribution middleware, which sees the same (surface, test) pair on every
-- request a test makes. COALESCE because test_file/test_case/test_run_id are legitimately NULL
-- for some evidence kinds, and PostgreSQL treats NULLs as distinct in a plain UNIQUE — which
-- would let the same edge insert without limit.
CREATE UNIQUE INDEX IF NOT EXISTS coverage_evidence_dedup
  ON harness_shared.coverage_evidence (
    surface_ref, evidence_kind,
    COALESCE(test_file, ''), COALESCE(test_case, ''), COALESCE(test_run_id, -1)
  );

-- The depth view's per-surface scan.
CREATE INDEX IF NOT EXISTS coverage_evidence_by_surface
  ON harness_shared.coverage_evidence (surface_ref, evidence_kind, observed_at DESC);

-- "Which surfaces did this run cover" — the completion-evidence and gap-queue read.
CREATE INDEX IF NOT EXISTS coverage_evidence_by_run
  ON harness_shared.coverage_evidence (test_run_id)
  WHERE test_run_id IS NOT NULL;

-- ---------------------------------------------------------------------------------------------
-- census_provider_registrations — which providers run for which pot. (D-004)
-- ---------------------------------------------------------------------------------------------
--
-- WHY POT-LEVEL AND NOT PLAN-LEVEL: the census is a standing property of a project, read by
-- gates, queues and panels between and across plans. Registering providers per-plan would mean
-- coverage exists only while some plan is active, and two plans could disagree about what the
-- project's surfaces ARE — reintroducing exactly the judgment variance the census removes. Plans
-- CONSUME the census (plan-touched scope) and may narrow what they are judged on; they never
-- define what exists.
CREATE TABLE IF NOT EXISTS harness_shared.census_provider_registrations (
    workspace_id text        NOT NULL,
    harness_slug text        NOT NULL,
    provider     text        NOT NULL,
    config       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    enabled      boolean     NOT NULL DEFAULT true,
    source       text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, harness_slug, provider)
);

COMMENT ON COLUMN harness_shared.census_provider_registrations.provider IS
  'Provider key, keyed by STACK not by project: hono-routes | mcp-tools | sync-queries | nuqs-states | tauri-webview | openapi-spec | next-routes | http-observed | ts-exports | agent-roles. Any pot on the same stack reuses the same provider (D-001).';
COMMENT ON COLUMN harness_shared.census_provider_registrations.source IS
  'How this registration arrived: template (the app-scope root declared it — templated apps are born measurable) | detected (harness:generate-from-repo stack sniffing) | manual (explicit operator/agent registration).';
COMMENT ON COLUMN harness_shared.census_provider_registrations.config IS
  'Provider-specific config — source globs, spec path, base URL, seam module. The provider CODE is shared; only this differs per pot.';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'census_provider_registrations_source_check') THEN
    ALTER TABLE harness_shared.census_provider_registrations
      ADD CONSTRAINT census_provider_registrations_source_check
      CHECK (source IN ('template', 'detected', 'manual'));
  END IF;
END $$;

-- ---------------------------------------------------------------------------------------------
-- coverage_waivers — the managed escape valve.
-- ---------------------------------------------------------------------------------------------
--
-- Every gate needs a managed escape valve, or it grows unmanaged ones (a second allowlist, an env
-- flag, a quietly-disabled check). expires_at is NOT NULL by design: this follows the
-- KNOWN_DARK_FLAGS governance — a waiver may exist, but it may not exist SILENTLY FOREVER.
CREATE TABLE IF NOT EXISTS harness_shared.coverage_waivers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surface_ref bigint      NOT NULL REFERENCES harness_shared.testing_surfaces (id) ON DELETE CASCADE,
    reason      text        NOT NULL,
    added_by    text        NOT NULL,
    expires_at  timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN harness_shared.coverage_waivers.reason IS
  'Why this surface is exempt. Required and free-text: an unexplained waiver is indistinguishable from an oversight, which is the thing being waived.';
COMMENT ON COLUMN harness_shared.coverage_waivers.expires_at IS
  'Hard expiry. NOT NULL so a waiver cannot linger silently (KNOWN_DARK_FLAGS governance) — when it lapses the gate speaks again on its own.';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'coverage_waivers_reason_check') THEN
    ALTER TABLE harness_shared.coverage_waivers
      ADD CONSTRAINT coverage_waivers_reason_check
      CHECK (length(btrim(reason)) >= 12);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS coverage_waivers_active
  ON harness_shared.coverage_waivers (surface_ref, expires_at DESC);

-- ---------------------------------------------------------------------------------------------
-- testing_surface_depth — the grading view. THE verdict surface.
-- ---------------------------------------------------------------------------------------------
--
-- WHY A VIEW AND NOT A STORED depth COLUMN: a stored grade goes stale the moment a test is
-- deleted or a run ages out, and a stale grade is a false pass. Recomputing from evidence on
-- every read cannot drift.
--
-- WHY BOOLEAN FLAGS AND NOT ONLY A NUMBER: the rungs are NOT strictly nested — a surface can have
-- an intent test (L3) while the fuzzer has never run against it (no L2). A gate that tested
-- `depth >= 3` would therefore be asking a question the data cannot answer. Gates test the FLAG
-- for the rung they require (meets_l3), and `depth` exists only as a human-facing summary of the
-- highest rung achieved.
--
-- WHY A FRESHNESS WINDOW: evidence is a claim about the CURRENT tree. A passing run from a test
-- file deleted three months ago is not evidence that anything is tested today, so evidence ages
-- out and the surface silently drops back down the ladder — which is the correct, self-correcting
-- behaviour. 30 days is the default; callers needing a different window query the base tables.
CREATE OR REPLACE VIEW harness_shared.testing_surface_depth AS
WITH fresh AS (
    SELECT e.*
      FROM harness_shared.coverage_evidence e
     WHERE e.observed_at > now() - interval '30 days'
),
graded AS (
    SELECT s.id AS surface_ref,
           -- L1 executed: something demonstrably reached it.
           bool_or(f.verdict = 'pass' AND f.evidence_kind IN ('traffic', 'file-coverage'))                     AS meets_l1,
           -- L2 conformant: a GENERATED adversarial suite passed against it.
           bool_or(f.verdict = 'pass' AND f.evidence_kind IN ('fuzz', 'crawl'))                                AS meets_l2,
           -- L3 intent-tested: a test a machine did NOT write demonstrably exercised it.
           bool_or(f.verdict = 'pass' AND f.generated = false
                                      AND f.evidence_kind IN ('traffic', 'file-coverage'))                     AS meets_l3,
           -- L4 hardened: the intent tests actually kill mutants.
           max(f.score) FILTER (WHERE f.evidence_kind = 'mutation')                                            AS mutation_score,
           count(*) FILTER (WHERE f.generated = false AND f.verdict = 'pass')                                  AS authored_evidence,
           max(f.observed_at)                                                                                  AS last_evidence_at
      FROM harness_shared.testing_surfaces s
      LEFT JOIN fresh f ON f.surface_ref = s.id
     GROUP BY s.id
)
SELECT s.id,
       s.workspace_id,
       s.harness_slug,
       s.kind,
       s.surface_id,
       s.source_file,
       s.provider,
       s.fidelity,
       s.first_seen,
       s.last_seen,
       s.retired_at,
       COALESCE(g.meets_l1, false)                                                AS meets_l1,
       COALESCE(g.meets_l2, false)                                                AS meets_l2,
       COALESCE(g.meets_l3, false)                                                AS meets_l3,
       (g.mutation_score IS NOT NULL AND g.mutation_score >= 0.6)                 AS meets_l4,
       g.mutation_score,
       COALESCE(g.authored_evidence, 0)                                           AS authored_evidence,
       g.last_evidence_at,
       CASE WHEN g.mutation_score IS NOT NULL AND g.mutation_score >= 0.6 THEN 4
            WHEN COALESCE(g.meets_l3, false)                                 THEN 3
            WHEN COALESCE(g.meets_l2, false)                                 THEN 2
            WHEN COALESCE(g.meets_l1, false)                                 THEN 1
            ELSE 0
       END                                                                        AS depth,
       EXISTS (SELECT 1
                 FROM harness_shared.coverage_waivers w
                WHERE w.surface_ref = s.id AND w.expires_at > now())              AS waived
  FROM harness_shared.testing_surfaces s
  LEFT JOIN graded g ON g.surface_ref = s.id;

COMMENT ON VIEW harness_shared.testing_surface_depth IS
  'THE coverage verdict surface: every censused surface with its achieved test depth, recomputed from evidence on every read (a stored grade would go stale into a false pass). Gates read the meets_lN FLAG for the rung they require — never depth >= N, because the rungs are not strictly nested (an intent-tested surface the fuzzer never ran against is L3 with no L2). Evidence older than 30 days is excluded, so a surface whose tests were deleted falls back down the ladder on its own.';
