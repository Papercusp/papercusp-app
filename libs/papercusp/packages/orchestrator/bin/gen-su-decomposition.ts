/**
 * gen:su-decomposition — (re)derive the su.md PART DOCUMENTS and the pinned
 * COMPOSITION_MODEL.md §9 from `src/blueprint/su-decomposition.ts` + the live
 * `blueprints/base/prompts/su.md` (identities-v1-2026-08-30 P-002).
 *
 *   npm run gen:su-decomposition          # write (from the superproject or libs/papercusp)
 *   npm run gen:su-decomposition:check    # exit 1 on drift
 *
 * The part documents are VERBATIM extractions (byte-equal to the concatenation of
 * their tiles) — never edit one by hand; edit su.md (or the tiling) and re-run.
 * `su-decomposition.test.ts` refuses drift, so a forgotten re-run fails the gate
 * with this command in the message. Lives under `bin/` (not `scripts/`) so the
 * package tsconfig compiles it — `lint:tsc:orchestrator` includes `bin/**`.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative } from 'node:path';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';
import { renderSuDecompositionMarkdown, suPartDocumentDrift, writeSuPartDocuments } from '../src/blueprint/su-decomposition.js';
import { resolveBlueprintSource, resolveBuiltinExtends } from '../src/blueprint/loader.js';
import { modeCatalogFromValidatedSources } from '../src/blueprint/mode-identities.js';
import { stableStringify } from '../src/blueprint/merge.js';

const here = dirname(fileURLToPath(import.meta.url));
const ORCHESTRATOR = join(here, '..');
const HARNESS = join(ORCHESTRATOR, '..', 'harness');
const DOC = join(ORCHESTRATOR, 'docs', 'COMPOSITION_MODEL.md');
const MODE_CATALOG = join(ORCHESTRATOR, 'src', 'blueprint', 'mode-catalog.generated.ts');
const BEGIN = '<!-- SU-DECOMPOSITION:BEGIN -->';
const END = '<!-- SU-DECOMPOSITION:END -->';

function splicedDoc(current: string): string {
  const re = new RegExp(`${BEGIN}[\\s\\S]*?${END}`);
  if (!re.test(current)) throw new Error(`${DOC} lacks the ${BEGIN} / ${END} markers — add a §9 with them first`);
  return current.replace(re, `${BEGIN}\n${renderSuDecompositionMarkdown()}\n${END}`);
}

/** A static, client-safe projection of the trusted built-in mode components.
 * The manifest/prompt files are the authored source; this file is a generated
 * compatibility view for the existing registry and browser imports. */
function renderModeCatalog(): string {
  const root = join(HARNESS, 'blueprints');
  const sources = readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => {
      const sourcePath = join(root, entry.name, 'blueprint.yaml');
      if (!existsSync(sourcePath)) return [];
      const raw = parseYaml(readFileSync(sourcePath, 'utf8')) as Record<string, unknown>;
      if (!raw || typeof raw !== 'object' || !raw.mode) return [];
      const mode = raw.mode as Record<string, unknown>;
      for (const field of ['implies', 'requiresSubject', 'launchable']) {
        if (mode[field] === undefined) throw new Error(`built-in mode ${entry.name} must declare ${field}`);
      }
      const source = resolveBlueprintSource(raw, { resolve: resolveBuiltinExtends, sourcePath });
      if (!source.validation.ok) {
        throw new Error(`mode source ${entry.name} invalid: ${source.validation.errors.map((issue) => issue.message).join('; ')}`);
      }
      return [source];
    });
  const policies = sources.flatMap((source) => source.layers.flatMap((layer) => layer.mode ? [layer.mode.policyRef] : []));
  const catalog = modeCatalogFromValidatedSources(sources, { supportedPolicyRefs: policies });
  const entries = catalog.entries.map((entry) => {
    const documentPath = `blueprints/${entry.sourceId}/prompts/${entry.slot}.md`;
    const definitionText = readFileSync(join(HARNESS, documentPath), 'utf8');
    if (!definitionText.trim()) throw new Error(`mode definition ${documentPath} is empty`);
    for (const alias of entry.aliases ?? []) {
      if (definitionText.split(alias.definitionHeading).length !== 2) {
        throw new Error(`mode alias ${alias.id} needs one definition heading in ${documentPath}`);
      }
    }
    return { ...entry, documentPath, definitionText,
      definitionHash: createHash('sha256').update(definitionText).digest('hex') };
  });
  const revision = createHash('sha256').update(stableStringify(entries)).digest('hex');
  return [
    '/** GENERATED by gen:su-decomposition from validated built-in mode manifests and prompts. DO NOT EDIT. */',
    `export const BUILTIN_MODE_CATALOG_REVISION = ${JSON.stringify(revision)} as const;`,
    `export const BUILTIN_MODE_COMPONENTS = ${JSON.stringify(entries, null, 2)} as const;`,
    '',
  ].join('\n');
}

const check = process.argv.includes('--check');
const cwd = process.cwd();
const doc = readFileSync(DOC, 'utf8');
const wantDoc = splicedDoc(doc);
const wantModeCatalog = renderModeCatalog();
const modeCatalogStale = !existsSync(MODE_CATALOG) || readFileSync(MODE_CATALOG, 'utf8') !== wantModeCatalog;
if (process.argv.includes('--mode-catalog-stdout')) {
  // A piped stdout can be nonblocking: stream backpressure instead of surfacing
  // EAGAIN from writeSync after emitting only part of the catalog.
  await pipeline(Readable.from([wantModeCatalog]), process.stdout);
  process.exit(0);
}
if (process.argv.includes('--mode-catalog-only')) {
  if (modeCatalogStale) writeFileSync(MODE_CATALOG, wantModeCatalog, 'utf8');
  console.log(modeCatalogStale ? `wrote ${relative(cwd, MODE_CATALOG)}` : 'mode catalog unchanged');
  process.exit(0);
}

if (check) {
  const drift = suPartDocumentDrift(HARNESS).filter((d) => d.status !== 'ok');
  const docStale = doc !== wantDoc;
  if (drift.length === 0 && !docStale && !modeCatalogStale) {
    console.log('gen:su-decomposition: up to date');
    process.exit(0);
  }
  for (const d of drift) console.error(`DRIFT ${d.status}: ${join('libs/papercusp/packages/harness', d.path)}`);
  if (docStale) console.error(`DRIFT stale: ${relative(cwd, DOC)} §9`);
  if (modeCatalogStale) console.error(`DRIFT stale: ${relative(cwd, MODE_CATALOG)}`);
  // This checker is also exposed from packages/operator-core, whose package.json
  // deliberately declares only the gate. Name the writer's real package boundary so
  // the remediation does not send callers to a nonexistent local npm script.
  console.error('run from the repository root or libs/papercusp: npm run gen:su-decomposition');
  process.exit(1);
}

for (const p of writeSuPartDocuments(HARNESS)) console.log(`wrote ${relative(cwd, p)}`);
if (doc !== wantDoc) {
  writeFileSync(DOC, wantDoc, 'utf8');
  console.log(`wrote ${relative(cwd, DOC)} §9`);
} else {
  console.log(`${relative(cwd, DOC)} §9 unchanged`);
}
if (modeCatalogStale) {
  writeFileSync(MODE_CATALOG, wantModeCatalog, 'utf8');
  console.log(`wrote ${relative(cwd, MODE_CATALOG)}`);
}
