/**
 * Where a part document LIVES — derived from its path, never restated (derived-truth
 * ladder rung 1). `identity` = under `blueprints/<identity-id>/prompts/`, the document
 * of an identity blueprint whose `slots:` names the part (P-020 resolves these through
 * the prompt chain); `base` = beside su.md under `blueprints/base/prompts/`.
 */
export function suPartDocumentHome(doc: Pick<SuPartDocument, 'path'>): 'identity' | 'base' {
  return doc.path.startsWith(`${BASE_ROLE_LIBRARY_REL}/`) ? 'base' : 'identity';
}

/** The identity blueprint id an identity-homed part document belongs to (`blueprints/<id>/…`). */
export function suPartDocumentBlueprintId(doc: Pick<SuPartDocument, 'path'>): string | null {
  const m = /^blueprints\/([^/]+)\/prompts\//.exec(doc.path);
  return suPartDocumentHome(doc) === 'identity' && m ? m[1]! : null;
}

export function suPartDocument(id: SuPartDocId): SuPartDocument {
  const d = SU_PART_DOCUMENTS.find((x) => x.id === id);
  if (!d) throw new Error(`unknown su part document ${id}`);
  return d;
}

/** The tiles a part document is the concatenation of, in su.md order. */
export function tilesOfDocument(located: readonly LocatedSuTile[], doc: SuPartDocument): LocatedSuTile[] {
  return located.filter((t) => t.part === doc.part && (doc.part !== 'fleet-posture' || t.posture === doc.posture));
}

/** The VERBATIM extraction — byte-equal to the concatenation of the document's tiles. */
export function extractSuPart(suText: string, id: SuPartDocId, tiles?: readonly SuTile[]): string {
  const doc = suPartDocument(id);
  return tilesOfDocument(locateSuTiles(suText, tiles), doc)
    .map((t) => t.text)
    .join('');
}

export function suSourcePath(harnessDir?: string): string {
  return harnessDir ? join(harnessDir, SU_SOURCE_REL) : harnessPath(...SU_SOURCE_REL.split('/'));
}

export function readSuSource(harnessDir?: string): string {
  return readFileSync(suSourcePath(harnessDir), 'utf8');
}

export function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

export interface SuPartDrift {
  id: SuPartDocId;
  path: string;
  status: 'ok' | 'missing' | 'stale';
}

/** Compare every committed part document with its derivation from the live su.md. */
export function suPartDocumentDrift(harnessDir?: string): SuPartDrift[] {
  const su = readSuSource(harnessDir);
  return SU_PART_DOCUMENTS.map((d) => {
    const abs = harnessDir ? join(harnessDir, d.path) : harnessPath(...d.path.split('/'));
    if (!existsSync(abs)) return { id: d.id, path: d.path, status: 'missing' as const };
    const want = extractSuPart(su, d.id);
    return { id: d.id, path: d.path, status: readFileSync(abs, 'utf8') === want ? ('ok' as const) : ('stale' as const) };
  });
}

/** (Re)write every part document from the live su.md; returns the paths written. */
export function writeSuPartDocuments(harnessDir?: string): string[] {
  const su = readSuSource(harnessDir);
  const out: string[] = [];
  for (const d of SU_PART_DOCUMENTS) {
    const abs = harnessDir ? join(harnessDir, d.path) : harnessPath(...d.path.split('/'));
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, extractSuPart(su, d.id), 'utf8');
    out.push(abs);
  }
  return out;
}

