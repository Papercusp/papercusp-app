/**
 * The su.md DECOMPOSITION — kernel / identity / instance boundary extraction as
 * SLOT ASSIGNMENTS over the live su base (`identities-v1-2026-08-30` P-002;
 * rulings D-003 as narrowed by D-007, the D-017 registry, D-018 §4 dedupe).
 *
 * WHAT THIS IS. `blueprints/base/prompts/su.md` is the LIVE su render source
 * (`role-launch-spec → resolvePromptFiles('su') → renderSuPlaybook`), and P-002
 * does NOT cut it — P-003 switches the render. What P-002 delivers is the
 * CLASSIFICATION: every line of su.md belongs to exactly one TILE, every tile is
 * assigned to one PART — the sealed `kernel`, the reserved `instance` layer, or
 * a declarable slot from `slots.ts` — and the parts are materialised as VERBATIM
 * documents (`SU_PART_DOCUMENTS`) that P-003's renderer composes and P-020 /
 * P-021 promote into identities. D-007: the output is slot assignments, not a
 * profession/facet type split.
 *
 * HOW A TILE IS ADDRESSED — by ANCHOR, not by line number. A tile is the run of
 * lines from its anchor (the exact text of its first line, unique in su.md) up
 * to the line before the next tile's anchor; the last tile runs to EOF. So the
 * tiling is complete by construction, an edit INSIDE a tile moves nothing, and
 * only a removed / duplicated / reordered anchor breaks it (`suTilingProblems`
 * says which). Two guards keep the classification honest as su.md evolves:
 * every `## ` / `### ` heading and every `<!-- PAPERCUSP-SU:… -->` splice
 * marker MUST be an anchor, so a NEW top-level section fails the test until it
 * is classified rather than silently inheriting its neighbour's slot. (A new
 * BULLET inside an existing tile does inherit — that is the granularity limit,
 * and the one place a reviewer still has to look.)
 *
 * THE PART DOCUMENTS ARE DERIVED, NOT AUTHORED. Each is byte-equal to the
 * concatenation of its tiles (`extractSuPart`), so the union of every part
 * document plus the seam tiles IS su.md — the lossless pin. They are committed
 * so an identity has a real file on disk (`papercusp-engineer`'s
 * `prompts/agent-base-overlay.md` is the coding hive's future `domain` leaf,
 * D-018 §5 / EI-22285277325728666), regenerated by
 * `npm run gen:su-decomposition`, and drift-checked by `su-decomposition.test.ts`
 * (derived-truth ladder: DERIVE, then PIN).
 *
 * D-018 §4 DEDUPE. `agent-base-preamble.md` is the kernel's BASE text rendered
 * on EVERY tier; su.md's ring-0 paragraphs are kernel EXTENSIONS of the
 * interactive tier. Where a tile duplicates a preamble section it carries
 * `dedupeWithPreamble` naming that heading — the text is KEPT here (su.md is
 * still the live render) and P-003 keeps it once, in the preamble.
 */
