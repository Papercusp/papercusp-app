/** A tile located in a concrete su.md text (1-indexed inclusive lines, text incl. trailing newline). */
export interface LocatedSuTile extends SuTile {
  index: number;
  startLine: number;
  endLine: number;
  text: string;
}

const SPLICE_MARKER_RE = /^<!-- PAPERCUSP-SU:[A-Z-]+ -->$/;
const HEADING_RE = /^##+ /;

/** Split keeping the trailing-newline contract explicit (su.md must end with `\n`). */
function suLines(text: string): string[] {
  if (!text.endsWith('\n')) throw new Error(`su.md must end with a newline (lossless tiling relies on it)`);
  const lines = text.split('\n');
  lines.pop();
  return lines;
}

/**
 * Structural problems with the tiling against THIS su.md text — empty means the
 * tiling is sound. Each message names the repair. Checked before any extraction.
 */
export function suTilingProblems(suText: string, tiles: readonly SuTile[] = SU_TILES): string[] {
  const problems: string[] = [];
  if (!suText.endsWith('\n')) return ['su.md must end with a newline'];
  const lines = suLines(suText);
  const positions: number[] = [];
  for (const t of tiles) {
    const hits: number[] = [];
    lines.forEach((l, i) => {
      if (l === t.anchor) hits.push(i + 1);
    });
    if (hits.length === 0) problems.push(`anchor not found — re-read that section of su.md and re-tile: ${JSON.stringify(t.anchor)}`);
    else if (hits.length > 1) problems.push(`anchor occurs ${hits.length}× (lines ${hits.join(', ')}) — an anchor must be unique: ${JSON.stringify(t.anchor)}`);
    else positions.push(hits[0]!);
  }
  if (problems.length) return problems;
  if (positions[0] !== 1) problems.push(`the first tile must start on line 1 (starts on ${positions[0]})`);
  for (let i = 1; i < positions.length; i++) {
    if (positions[i]! <= positions[i - 1]!) problems.push(`tiles out of order: ${JSON.stringify(tiles[i]!.anchor)} (line ${positions[i]}) is not after ${JSON.stringify(tiles[i - 1]!.anchor)} (line ${positions[i - 1]})`);
  }
  const anchorSet = new Set(tiles.map((t) => t.anchor));
  lines.forEach((l, i) => {
    if (HEADING_RE.test(l) && !anchorSet.has(l)) problems.push(`heading on line ${i + 1} is not a tile anchor — classify it in SU_TILES: ${JSON.stringify(l)}`);
    if (SPLICE_MARKER_RE.test(l) && !anchorSet.has(l)) problems.push(`splice marker on line ${i + 1} is not a tile anchor — classify it in SU_TILES: ${JSON.stringify(l)}`);
  });
  for (const t of tiles) {
    if (t.seam && !SPLICE_MARKER_RE.test(t.anchor)) problems.push(`tile declares seam ${t.seam} but its anchor is not a splice marker: ${JSON.stringify(t.anchor)}`);
    if (t.seam && t.anchor !== `<!-- PAPERCUSP-SU:${t.seam} -->`) problems.push(`seam name ${t.seam} does not match its marker ${JSON.stringify(t.anchor)}`);
    if (t.part === 'fleet-posture' && !t.posture) problems.push(`fleet-posture tile must name its posture: ${JSON.stringify(t.anchor)}`);
    if (t.part !== 'fleet-posture' && t.posture) problems.push(`only fleet-posture tiles carry a posture: ${JSON.stringify(t.anchor)}`);
    if (!isSuPart(t.part)) problems.push(`unknown part ${JSON.stringify(t.part)} on ${JSON.stringify(t.anchor)}`);
  }
  return problems;
}

/** Resolve every tile to its line range + text in THIS su.md; throws on a tiling problem. */
export function locateSuTiles(suText: string, tiles: readonly SuTile[] = SU_TILES): LocatedSuTile[] {
  const problems = suTilingProblems(suText, tiles);
  if (problems.length) throw new Error(`su.md tiling is unsound:\n  - ${problems.join('\n  - ')}`);
  const lines = suLines(suText);
  const starts = tiles.map((t) => lines.indexOf(t.anchor) + 1);
  return tiles.map((t, i) => {
    const startLine = starts[i]!;
    const endLine = i + 1 < starts.length ? starts[i + 1]! - 1 : lines.length;
    return { ...t, index: i, startLine, endLine, text: lines.slice(startLine - 1, endLine).join('\n') + '\n' };
  });
}

