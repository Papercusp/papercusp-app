/**
 * React + Tailwind tokens surface.
 *
 * Two emissions from a DTCG doc:
 *   1. CSS custom properties (`design-tokens.css`)
 *   2. Tailwind preset extension (`tailwind.tokens.ts`)
 *
 * v0.1 handles `color` and `dimension` types directly. Other types
 * (typography, shadow, cubicBezier, etc.) emit as raw CSS vars without
 * Tailwind mapping — adapter authors can extend later.
 *
 * Terrazzo (the planned long-term transformer) is not yet a dep. This
 * minimal in-house emitter keeps the spine independent of external
 * tooling for v0.1.
 */
import type { DtcgDoc, DtcgToken, FileEmit, TokensSurface } from '../design-adapter';

function escapeCssValue(v: unknown): string {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  return JSON.stringify(v);
}

function tokenIdToCssVar(id: string): string {
  // color.bg.surface → --color-bg-surface
  return `--${id.replace(/\./g, '-').replace(/[^a-zA-Z0-9-]/g, '-')}`;
}

function tokenIdToTailwindPath(id: string): string[] {
  // color.bg.surface → ['color', 'bg', 'surface'] → tailwind nested
  return id.split('.');
}

function emitCssVars(tokens: ReadonlyArray<DtcgToken>): string {
  const lines = ['/* Generated by papercusp-design-react-tailwind. Do not edit by hand. */', ':root {'];
  for (const t of tokens) {
    lines.push(`  ${tokenIdToCssVar(t.id)}: ${escapeCssValue(t.value)};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

function setNested(target: Record<string, unknown>, path: string[], value: unknown): void {
  let cur = target;
  for (let i = 0; i < path.length - 1; i++) {
    const k = path[i];
    if (!(k in cur) || typeof cur[k] !== 'object' || cur[k] === null) {
      cur[k] = {};
    }
    cur = cur[k] as Record<string, unknown>;
  }
  cur[path[path.length - 1]] = value;
}

function emitTailwindPreset(tokens: ReadonlyArray<DtcgToken>): string {
  const colors: Record<string, unknown> = {};
  const spacing: Record<string, unknown> = {};
  const fontFamily: Record<string, unknown> = {};
  const fontWeight: Record<string, unknown> = {};
  const transitionDuration: Record<string, unknown> = {};

  for (const t of tokens) {
    const path = tokenIdToTailwindPath(t.id);
    const cssVar = `var(${tokenIdToCssVar(t.id)})`;
    switch (t.type) {
      case 'color':
        // color.bg.surface → colors.bg.surface (drop leading 'color' bucket)
        if (path[0] === 'color') {
          setNested(colors, path.slice(1), cssVar);
        } else {
          setNested(colors, path, cssVar);
        }
        break;
      case 'dimension':
        // dimension|space|size buckets → spacing.{rest}
        if (['dimension', 'space', 'size'].includes(path[0])) {
          setNested(spacing, path.slice(1), cssVar);
        } else {
          setNested(spacing, path, cssVar);
        }
        break;
      case 'fontFamily':
        if (path[0] === 'font' || path[0] === 'fontFamily') {
          setNested(fontFamily, path.slice(1), cssVar);
        } else {
          setNested(fontFamily, path, cssVar);
        }
        break;
      case 'fontWeight':
        if (path[0] === 'font' || path[0] === 'fontWeight') {
          setNested(fontWeight, path.slice(1), cssVar);
        } else {
          setNested(fontWeight, path, cssVar);
        }
        break;
      case 'duration':
        if (path[0] === 'duration') {
          setNested(transitionDuration, path.slice(1), cssVar);
        } else {
          setNested(transitionDuration, path, cssVar);
        }
        break;
      default:
        // shadow/cubicBezier/number — pass through but no tailwind mapping
        break;
    }
  }

  const theme: Record<string, unknown> = {};
  if (Object.keys(colors).length) theme['colors'] = colors;
  if (Object.keys(spacing).length) theme['spacing'] = spacing;
  if (Object.keys(fontFamily).length) theme['fontFamily'] = fontFamily;
  if (Object.keys(fontWeight).length) theme['fontWeight'] = fontWeight;
  if (Object.keys(transitionDuration).length) theme['transitionDuration'] = transitionDuration;

  return [
    '// Generated by papercusp-design-react-tailwind. Do not edit by hand.',
    "import type { Config } from 'tailwindcss';",
    '',
    'const tokens: Partial<Config[\'theme\']> = {',
    `  extend: ${JSON.stringify(theme, null, 2)},`,
    '};',
    '',
    'export default tokens;',
    '',
  ].join('\n');
}

export function makeReactTailwindTokens(opts: {
  cssVarsOutPath?: string;
  tailwindPresetOutPath?: string;
} = {}): TokensSurface {
  const cssOut = opts.cssVarsOutPath ?? 'design/generated/design-tokens.css';
  const twOut = opts.tailwindPresetOutPath ?? 'design/generated/tailwind.tokens.ts';
  return {
    async emit(dtcg: DtcgDoc): Promise<FileEmit[]> {
      return [
        { path: cssOut, contents: emitCssVars(dtcg.tokens), overwrite: true },
        { path: twOut, contents: emitTailwindPreset(dtcg.tokens), overwrite: true },
      ];
    },
  };
}

export const _internal = { emitCssVars, emitTailwindPreset, tokenIdToCssVar };
