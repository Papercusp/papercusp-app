/**
 * `system:project-history-refresh` — the refresh owner for a hive's committed
 * Project History artifact (EI-20475585438015488, cause 3).
 *
 * WHY THIS EXISTS. A hive that ships a History tab serves it from a GENERATED
 * artifact committed into that hive's repo (SideStage: `apps/api/src/build-history/
 * build-history.snapshot.ts`, ~2.2MB of rendered plan history). The artifact is
 * produced by `papercusp project-history generate`, which reads plans + work-items
 * out of Postgres — data the hive's own service deliberately cannot reach at
 * runtime (the public repo must build and run with no operator and no PG). That
 * split is correct, but it leaves the artifact with NO refresh owner: it was
 * generated by hand, and from that moment it only ever got staler. When
 * EI-20475585438015488 was opened the committed snapshot had drifted ~2 days and
 * was ALSO polluted with 17 `acceptance-*` template-carrier plans; the History tab
 * presented that stale, polluted set as the project's complete archive, with
 * nothing anywhere reporting that it was behind.
 *
 * Fixing the snapshot's CONTENT (done: planCount 62 -> 51, acceptance-* 17 -> 0)
 * is a mitigation, not a fix — nothing regenerates it, so it rots again. This
 * routine is the durable half: it is the thing that OWNS the artifact's freshness.
 *
 * WHY A ROUTINE AND NOT A BUILD STEP. Three constraints settled during the
 * investigation, each of which rules out an easier-looking option:
 *   - NOT `npm run build`. The hive's public repo must build with no operator,
 *     no `ptool`, and no database. Hanging generation off `build` makes a
 *     PG-reachable operator a build dependency of a public repo.
 *   - NOT a runtime PG read in the hive service. Same reason, and it would put a
 *     cross-tenant database dependency behind a public HTTP surface.
 *   - NOT a bare `setInterval` (`lint:no-raw-setinterval`) and not a hand-rolled
 *     scheduler. `tier:'durable'` + `routinesTick` is the mechanism this repo
 *     already has for scheduled, Postgres-backed, operator-visible work.
 *
 * WHY IT IS GENERIC RATHER THAN `system:sidestage-history-refresh`. Nothing here
 * is SideStage-specific: every field the generator needs (harness, plan prefix,
 * project id/name, repo root, output path, format, export name) is already a CLI
 * option, so they are all `trigger_config` keys. SideStage is simply the first
 * hive to seed a row. A second hive that ships a History artifact seeds another
 * row and needs no code. Naming one app in operator-core would have been the
 * wrong altitude, and it is the kind of thing that is very hard to un-name later.
 *
 * ⚠ THE PATH TRAP THIS DELIBERATELY AVOIDS — read before "simplifying" the two
 * resolvers below. The generation path depends on TWO external executables, and
 * they behave differently under a routine than under an interactive agent shell:
 *
 *   1. `papercusp` — MUST be pinned, never taken from PATH. The installed
 *      dispatcher at `~/.papercusp/bin/papercusp` is REGENERATED on every boot
 *      and was observed FLAPPING: the `project-history` route was present at
 *      18:2x and absent (exit 2) at 19:0x the same evening. Worse, the operator
 *      service's own PATH does not contain `~/.papercusp/bin` at all
 *      (measured: its PATH is linuxbrew:cargo:~/.local/bin:~/bin:/usr/local/...),
 *      so a bare `papercusp` from a routine resolves to NOTHING even when it
 *      works fine in an agent's terminal. We resolve the in-tree CLI bin instead,
 *      which is version-locked to this checkout.
 *   2. `ptool` — cannot be pinned, so it is PRECHECKED. `project-history-cli.ts`
 *      shells out to a bare `'ptool'` (hardcoded, no env override) for every plan
 *      and work-item read. It resolves today at `~/.local/bin/ptool`, which IS on
 *      the operator service's PATH — but that is a property of this box's
 *      environment, not a guarantee. If it ever stops resolving, the generator
 *      fails partway through its reads, and the failure mode we care about is a
 *      TRUNCATED-but-valid artifact silently replacing a good one. So we check
 *      that `ptool` resolves BEFORE spawning and refuse the tick loudly if it
 *      does not, rather than discovering it from a short snapshot.
 *
 * Bounded + fail-soft, mirroring gitnexus-reindex-action.ts / cargo-test-action.ts:
 * the child is its own process-group leader so a timeout kills the whole tree
 * (bash wrapper -> tsx -> node -> the ptool children it spawns), never just the
 * wrapper, and a wedged generation can therefore never wedge the routines tick.
 * A consecutive-failure streak is persisted to the routine's metadata and raises
 * an attention notification past the threshold, because the whole point of this
 * routine is that a silently-not-running refresher is indistinguishable from the
 * unowned decay it was built to end.
 */
import { spawn } from 'node:child_process';
import * as path from 'node:path';
import { existsSync, accessSync, constants as fsConstants } from 'node:fs';
import { registerSystemAction, type SystemActionCtx } from './system-actions';
import { collectChildOutput } from '../../child-output';

/** Generation walks every plan + work-item for the harness and renders a multi-MB
 *  artifact; SideStage's ~51-plan archive runs well under a minute, but a larger
 *  harness on a busy box needs real headroom. This bounds a WEDGED run, and is not
 *  a target. */
export const PROJECT_HISTORY_TIMEOUT_MS = 15 * 60_000;

/** Raise an operator notification once a streak reaches this length. Two is
 *  deliberate: a single failure is usually a transient (PG restart, a deploy
 *  mid-tick), while two consecutive means the refresher itself is broken and the
 *  artifact has resumed the exact unowned decay this routine exists to end. */
export const PROJECT_HISTORY_FAILURE_ALERT_THRESHOLD = 2;

export interface ProjectHistoryHealth {
  consecutiveFailures: number;
  lastOkAt: string | null;
  lastFailureAt: string | null;
  alerted: boolean;
}

export const PROJECT_HISTORY_HEALTH_DEFAULT: ProjectHistoryHealth = {
  consecutiveFailures: 0,
  lastOkAt: null,
  lastFailureAt: null,
  alerted: false,
};

/** `env` is threaded rather than read off `process.env` so the resolvers below stay
 *  testable — an env-reading resolver that ignores its own argument is a silent
 *  footgun for every caller that thinks it injected one. */
export function integrationRoot(env: NodeJS.ProcessEnv = process.env): string {
  return env.PAPERCUSP_INTEGRATION_ROOT ?? path.resolve(process.cwd(), '..', '..');
}

/**
 * The in-tree Papercusp CLI bin, version-locked to this checkout.
 *
 * `PAPERCUSP_CLI` overrides it (the same env var `generate-build-history-snapshot.mjs`
 * already honours, so an operator can point both at one binary). We deliberately do
 * NOT fall back to a bare `'papercusp'`: see the PATH TRAP note in the file header —
 * an ambient fallback is exactly the failure this resolver exists to prevent, and a
 * fallback that "usually works" is worse than none, because it fails only sometimes.
 */
export function resolveCliBin(env: NodeJS.ProcessEnv = process.env): string {
  const pinned = env.PAPERCUSP_CLI?.trim();
  if (pinned) return pinned;
  return path.join(integrationRoot(env), 'libs', 'papercusp', 'packages', 'cli', 'bin', 'papercusp');
}

/**
 * Does `ptool` resolve on the child's PATH? Returns the resolved path, or null.
 *
 * Pure w.r.t. its inputs (PATH string + an existence probe) so the precondition is
 * testable without depending on the box's real environment.
 */
export function resolvePtool(
  env: NodeJS.ProcessEnv = process.env,
  isExecutable: (p: string) => boolean = defaultIsExecutable,
): string | null {
  const explicit = env.PAPERCUSP_PTOOL?.trim();
  if (explicit) return isExecutable(explicit) ? explicit : null;
  for (const dir of (env.PATH ?? '').split(path.delimiter)) {
    if (!dir) continue;
    const candidate = path.join(dir, 'ptool');
    if (isExecutable(candidate)) return candidate;
  }
  return null;
}

function defaultIsExecutable(p: string): boolean {
  try {
    accessSync(p, fsConstants.X_OK);
    return true;
  } catch {
    return false;
  }
}

export interface ProjectHistoryConfig {
  workspace: string;
  harness: string;
  planPrefix: string;
  projectId: string;
  projectName: string;
  repoRoot: string;
  output: string;
  format: 'json' | 'typescript';
  exportName: string;
}

function str(cfg: Record<string, unknown>, key: string): string | null {
  const v = cfg[key];
  return typeof v === 'string' && v.trim().length > 0 ? v.trim() : null;
}

function num(cfg: Record<string, unknown>, key: string, fallback: number): number {
  const v = cfg[key];
  return typeof v === 'number' && Number.isFinite(v) ? v : fallback;
}

/**
 * Read the routine's `trigger_config` into a fully-resolved generation config, or
 * return the reason it cannot be resolved.
 *
 * `repo_root` and `output` are REQUIRED and have no defaults on purpose. Everything
 * else can be defaulted safely from the harness slug, but guessing a repo root or an
 * output path would let a misconfigured row write a multi-MB artifact to the wrong
 * place in someone else's tree — a mistake that git-sync would then dutifully commit.
 * A loud refusal is the correct behaviour for both.
 *
 * `plan_prefix` defaults to EMPTY, not to `<harness>-`. The CLI's own default is
 * `<harness>-`, but every hive seeded so far wants the whole harness's plan set
 * (SideStage passes `--prefix=`); a silent prefix filter is the failure mode that
 * makes an archive look complete while omitting most of it.
 */
export function resolveProjectHistoryConfig(
  cfg: Record<string, unknown>,
  installSlug: string,
  workspaceId: string,
): { ok: true; config: ProjectHistoryConfig } | { ok: false; reason: string } {
  const repoRoot = str(cfg, 'repo_root');
  if (!repoRoot) return { ok: false, reason: 'trigger_config.repo_root is required (absolute path to the hive repo)' };
  if (!path.isAbsolute(repoRoot)) return { ok: false, reason: `trigger_config.repo_root must be absolute, got "${repoRoot}"` };

  const output = str(cfg, 'output');
  if (!output) return { ok: false, reason: 'trigger_config.output is required (artifact path, relative to repo_root or absolute)' };

  const rawFormat = str(cfg, 'format') ?? (output.endsWith('.ts') ? 'typescript' : 'json');
  if (rawFormat !== 'json' && rawFormat !== 'typescript') {
    return { ok: false, reason: `trigger_config.format must be "json" or "typescript", got "${rawFormat}"` };
  }

  return {
    ok: true,
    config: {
      workspace: str(cfg, 'workspace') ?? workspaceId,
      harness: str(cfg, 'harness') ?? installSlug,
      planPrefix: typeof cfg.plan_prefix === 'string' ? cfg.plan_prefix : '',
      projectId: str(cfg, 'project_id') ?? installSlug,
      projectName: str(cfg, 'project_name') ?? installSlug,
      repoRoot,
      output: path.isAbsolute(output) ? output : path.join(repoRoot, output),
      format: rawFormat,
      exportName: str(cfg, 'export_name') ?? 'PROJECT_HISTORY',
    },
  };
}

/**
 * The argv handed to `papercusp project-history`. Single construction site so the
 * shape is asserted by one test rather than trusted at each call site.
 *
 * ⚠ `--prefix=<value>` is written in the `=` form on purpose so an EMPTY prefix is
 * passed as an empty value rather than swallowing the next token as its argument.
 * `--prefix ''` would work through a shell but this is an argv spawn with no shell,
 * and the `=` form is unambiguous either way.
 */
export function buildProjectHistoryArgs(config: ProjectHistoryConfig): string[] {
  return [
    'project-history',
    'generate',
    '--workspace', config.workspace,
    '--harness', config.harness,
    `--prefix=${config.planPrefix}`,
    '--project-id', config.projectId,
    '--project-name', config.projectName,
    '--repo', config.repoRoot,
    '--output', config.output,
    '--format', config.format,
    '--export-name', config.exportName,
  ];
}

export interface GenerateRunResult {
  code: number;
  stdout: string;
  stderr: string;
  timedOut: boolean;
}

/**
 * Spawn the generator, bounded by `timeoutMs`.
 *
 * `detached: true` makes the child its own process-group leader purely so the
 * timeout can kill the WHOLE tree — the CLI bin is a bash wrapper that execs tsx,
 * which spawns a `ptool` child per read, so killing the wrapper alone would orphan
 * live workers. Allowlisted in `scripts/check-no-unenrolled-detached-spawn.mjs`
 * with this reason; same precedent as gitnexus-reindex-action.ts.
 */
export function runProjectHistoryGenerate(
  cliBin: string,
  config: ProjectHistoryConfig,
  timeoutMs: number,
  env: NodeJS.ProcessEnv = process.env,
): Promise<GenerateRunResult> {
  return new Promise((resolvePromise) => {
    const child = spawn(cliBin, buildProjectHistoryArgs(config), {
      cwd: config.repoRoot,
      env,
      detached: true,
    });
    // Chunk-safe accumulation: a multi-byte UTF-8 character split across two
    // 'data' events must not decode to replacement chars (WI-6728).
    const { stdout: outCollector, stderr: errCollector } = collectChildOutput(child);
    let timedOut = false;
    let escalate: NodeJS.Timeout | null = null;
    const killTree = (sig: NodeJS.Signals): void => {
      try {
        if (child.pid) process.kill(-child.pid, sig);
      } catch {
        try {
          child.kill(sig);
        } catch {
          /* already dead */
        }
      }
    };
    const killer = setTimeout(() => {
      timedOut = true;
      killTree('SIGTERM');
      escalate = setTimeout(() => killTree('SIGKILL'), 15_000);
      escalate.unref();
    }, timeoutMs);
    const finish = (res: GenerateRunResult): void => {
      clearTimeout(killer);
      if (escalate) clearTimeout(escalate);
      resolvePromise(res);
    };
    child.on('error', (e) => {
      errCollector.append(String(e));
      finish({ code: 1, stdout: outCollector.text(), stderr: errCollector.text(), timedOut });
    });
    child.on('close', (code) =>
      finish({
        code: code ?? 1,
        stdout: outCollector.text(),
        stderr: errCollector.text(),
        timedOut,
      }),
    );
  });
}

export interface HealthUpdate {
  next: ProjectHistoryHealth;
  shouldAlert: boolean;
  shouldResolve: boolean;
}

/**
 * Fold one run's outcome into the persisted streak. Pure so the alert/resolve edges
 * are testable without a database.
 *
 * `alerted` latches so a long outage raises ONE notification rather than one per
 * tick, and clears on the first success so a later outage can alert again.
 */
export function decideProjectHistoryHealthUpdate(
  prev: ProjectHistoryHealth,
  success: boolean,
  threshold: number,
  nowMs: number,
): HealthUpdate {
  const nowIso = new Date(nowMs).toISOString();
  if (success) {
    return {
      next: { consecutiveFailures: 0, lastOkAt: nowIso, lastFailureAt: prev.lastFailureAt, alerted: false },
      shouldAlert: false,
      shouldResolve: prev.consecutiveFailures > 0,
    };
  }
  const consecutiveFailures = prev.consecutiveFailures + 1;
  return {
    next: { consecutiveFailures, lastOkAt: prev.lastOkAt, lastFailureAt: nowIso, alerted: prev.alerted || consecutiveFailures >= threshold },
    shouldAlert: consecutiveFailures >= threshold && !prev.alerted,
    shouldResolve: false,
  };
}

registerSystemAction('project-history-refresh', async (ctx: SystemActionCtx) => {
  const cfg = ctx.triggerConfig ?? {};
  const resolved = resolveProjectHistoryConfig(cfg, ctx.installSlug, ctx.workspaceId);
  if (!resolved.ok) {
    // A misconfigured row can never be fixed by retrying, so this is a loud,
    // non-throwing refusal: it must not fail the whole routines tick for its peers.
    console.error(`[project-history-refresh] MISCONFIGURED on "${ctx.installSlug}": ${resolved.reason}`);
    return;
  }
  const config = resolved.config;

  if (!existsSync(config.repoRoot)) {
    console.error(`[project-history-refresh] skip: repo_root does not exist: ${config.repoRoot}`);
    return;
  }

  // PRECONDITION 1 — the pinned CLI. Never an ambient PATH lookup (file header).
  const cliBin = resolveCliBin();
  if (!existsSync(cliBin)) {
    console.error(
      `[project-history-refresh] ABORT: Papercusp CLI not found at "${cliBin}". ` +
        'Set PAPERCUSP_CLI to the CLI bin, or check the integration root. ' +
        'Refusing to fall back to a PATH lookup — the installed dispatcher is regenerated per boot and flaps.',
    );
    return;
  }

  // PRECONDITION 2 — `ptool`, which the generator shells out to for every read and
  // which has no env override of its own. Checked BEFORE spawning so a missing
  // binary is reported as a missing binary, rather than as a short artifact.
  const ptool = resolvePtool();
  if (!ptool) {
    console.error(
      '[project-history-refresh] ABORT: `ptool` does not resolve on PATH. ' +
        'project-history-cli.ts shells out to a bare `ptool` for every plan/work-item read, so ' +
        'generation would fail partway and could write a TRUNCATED artifact over a good one. ' +
        `Set PAPERCUSP_PTOOL, or add its directory to the operator service PATH. (PATH=${process.env.PATH ?? ''})`,
    );
    return;
  }

  const timeoutMs = num(cfg, 'timeout_ms', PROJECT_HISTORY_TIMEOUT_MS);
  const startedAt = Date.now();
  console.log(
    `[project-history-refresh] generating ${config.projectId} history -> ${config.output} ` +
      `(harness=${config.harness} prefix="${config.planPrefix}" cli=${cliBin} ptool=${ptool})`,
  );
  const r = await runProjectHistoryGenerate(cliBin, config, timeoutMs);
  const elapsedSec = Math.round((Date.now() - startedAt) / 1000);
  const success = !r.timedOut && r.code === 0;

  if (r.timedOut) {
    console.warn(`[project-history-refresh] TIMED OUT after ${timeoutMs}ms (${elapsedSec}s) — process tree killed`);
  } else if (r.code !== 0) {
    console.warn(`[project-history-refresh] exited ${r.code} after ${elapsedSec}s — ${(r.stderr || r.stdout).slice(-500)}`);
  } else {
    console.log(`[project-history-refresh] ok in ${elapsedSec}s — ${config.output}`);
  }

  // Persist the streak and alert past the threshold. Fail-soft: a DB or notify
  // hiccup must never fail the tick — it only costs this tick's bookkeeping, which
  // the next tick re-derives.
  try {
    const { getOrgPg } = await import('@papercusp/db-org');
    const { sql } = getOrgPg();
    const rows = (await sql.unsafe(
      `SELECT metadata->'project_history_health' AS ph FROM harness_shared.routines
        WHERE install_slug = $1 AND target_role = 'system:project-history-refresh'`,
      [ctx.installSlug],
    )) as Array<{ ph: Partial<ProjectHistoryHealth> | null }>;
    const prevHealth: ProjectHistoryHealth = { ...PROJECT_HISTORY_HEALTH_DEFAULT, ...(rows[0]?.ph ?? {}) };
    const update = decideProjectHistoryHealthUpdate(prevHealth, success, PROJECT_HISTORY_FAILURE_ALERT_THRESHOLD, Date.now());
    await sql.unsafe(
      `UPDATE harness_shared.routines
          SET metadata = COALESCE(metadata, '{}'::jsonb) || $2::jsonb, updated_at = now()
        WHERE install_slug = $1 AND target_role = 'system:project-history-refresh'`,
      [ctx.installSlug, JSON.stringify({ project_history_health: update.next })],
    );
    if (update.shouldAlert) {
      const { notifyAttention } = await import('../../attention-notify');
      await notifyAttention({
        kind: 'intervention',
        title: 'project-history-refresh failing — the History artifact is going stale again',
        body:
          `system:project-history-refresh has now failed ${update.next.consecutiveFailures} consecutive time(s) on ` +
          `${ctx.installSlug}. The committed History artifact (${config.output}) is no longer being refreshed, which is ` +
          'the exact unowned-decay condition EI-20475585438015488 was filed for. Latest failure: ' +
          `${r.timedOut ? `timed out after ${timeoutMs}ms` : `exited ${r.code}`} — ${(r.stderr || r.stdout).slice(-300)}`,
        importance: 'urgent',
        workspaceId: ctx.workspaceId,
        harnessSlug: ctx.installSlug,
        data: { consecutiveFailures: update.next.consecutiveFailures, timedOut: r.timedOut, code: r.code, output: config.output },
      });
    } else if (update.shouldResolve) {
      console.log(`[project-history-refresh] recovered after a ${prevHealth.consecutiveFailures}-failure streak`);
    }
  } catch (e) {
    console.warn(`[project-history-refresh] health bookkeeping skipped: ${e instanceof Error ? e.message : String(e)}`);
  }
});
