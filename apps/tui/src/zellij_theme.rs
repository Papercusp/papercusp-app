//! zellij chrome sync (workbench-theme-system-2026-06-05 P2 / D-003).
//!
//! From each [`ThemeSpec`] this module **generates** the matching zellij theme
//! KDL (the 0.40+ component spec — verified against the v0.44.3 asset themes)
//! and installs the files **additively** into the standard zellij themes dir
//! (one file per theme, marker-guarded — a user's own theme file with the same
//! name is never clobbered). Selection is a **single pui-managed
//! `theme "<name>"` line** in the user's `config.kdl`, comment-marked; zellij's
//! config watcher re-themes the chrome the same instant pui re-renders its
//! content. Explicitly rejected (D-003): launching zellij with a pui-owned
//! `--config` — that would replace the user's whole config including keybinds.
//!
//! Risk handling (plan §Risks): `config.kdl` is backed up once (first managed
//! write) to `config.kdl.pui-bak`; if the user has their *own* uncommented
//! `theme` line (no pui marker), it is respected — reported, never rewritten.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use ratatui::style::Color;

use crate::theme::{ThemeSpec, THEMES};

/// Marker on the single managed selection line in `config.kdl`.
pub const MANAGED_MARKER: &str = "// managed by pui :theme";
/// Header marking a theme file as pui-generated (safe to regenerate).
const GENERATED_HEADER: &str =
    "// generated by pui :theme (workbench-theme-system) — edits are overwritten";

/// What a sync did, for the run loop's toast.
#[derive(Debug, PartialEq, Eq)]
pub struct SyncOutcome {
    /// Theme files written (new or regenerated pui-owned).
    pub installed: Vec<String>,
    /// Theme names whose file exists but is NOT pui-generated — left alone.
    pub skipped: Vec<String>,
    pub config: ConfigOutcome,
}

#[derive(Debug, PartialEq, Eq)]
pub enum ConfigOutcome {
    /// The managed `theme` line was written/updated (chrome flips live).
    Set,
    /// The user has their own un-marked `theme "<name>"` line — respected;
    /// the chrome stays on their choice (D-003 risk rule).
    RespectedUser(String),
}

/// The zellij config dir: `$ZELLIJ_CONFIG_DIR` override, else
/// `~/.config/zellij` (zellij's default on Linux).
pub fn zellij_config_dir() -> Option<PathBuf> {
    if let Ok(d) = std::env::var("ZELLIJ_CONFIG_DIR") {
        if !d.trim().is_empty() {
            return Some(PathBuf::from(d));
        }
    }
    dirs::home_dir().map(|h| h.join(".config").join("zellij"))
}

/// Full `:theme <name>` chrome sync against the standard zellij config dir:
/// regenerate + install every built-in theme file, then point the managed
/// `theme` line at `name`.
pub fn sync(name: &str) -> io::Result<SyncOutcome> {
    let dir = zellij_config_dir()
        .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "no home dir"))?;
    sync_in(&dir, name)
}

/// [`sync`] against an explicit config dir (unit tests use a temp dir).
pub fn sync_in(config_dir: &Path, name: &str) -> io::Result<SyncOutcome> {
    let (installed, skipped) = install_themes(&config_dir.join("themes"))?;
    let config = set_config_theme_line(&config_dir.join("config.kdl"), name)?;
    Ok(SyncOutcome {
        installed,
        skipped,
        config,
    })
}

// ─── KDL generation ──────────────────────────────────────────────────────────

/// A `ThemeSpec` slot as the `r g b` triplet zellij's KDL wants. The specs are
/// `Color::Rgb` throughout except a couple of named-ANSI slots (e.g.
/// papercusp-dark's `on_accent: Color::Black`), mapped via the standard
/// palette; anything exotic falls back to mid-grey rather than failing the
/// whole generation.
fn rgb(c: Color) -> (u8, u8, u8) {
    match c {
        Color::Rgb(r, g, b) => (r, g, b),
        Color::Black => (0, 0, 0),
        Color::Red => (205, 49, 49),
        Color::Green => (13, 188, 121),
        Color::Yellow => (229, 229, 16),
        Color::Blue => (36, 114, 200),
        Color::Magenta => (188, 63, 188),
        Color::Cyan => (17, 168, 205),
        Color::Gray => (229, 229, 229),
        Color::DarkGray => (102, 102, 102),
        Color::LightRed => (241, 76, 76),
        Color::LightGreen => (35, 209, 139),
        Color::LightYellow => (245, 245, 67),
        Color::LightBlue => (59, 142, 234),
        Color::LightMagenta => (214, 112, 214),
        Color::LightCyan => (41, 184, 219),
        Color::White => (255, 255, 255),
        _ => (128, 128, 128),
    }
}

fn fmt_color(c: Color) -> String {
    let (r, g, b) = rgb(c);
    format!("{r} {g} {b}")
}

/// One component block (`text_unselected { base …; background …; emphasis_0..3 }`).
fn component(out: &mut String, name: &str, base: Color, background: Color, emphasis: [Color; 4]) {
    out.push_str(&format!("        {name} {{\n"));
    out.push_str(&format!("            base {}\n", fmt_color(base)));
    out.push_str(&format!(
        "            background {}\n",
        fmt_color(background)
    ));
    for (i, e) in emphasis.iter().enumerate() {
        out.push_str(&format!("            emphasis_{i} {}\n", fmt_color(*e)));
    }
    out.push_str("        }\n");
}

/// The zellij theme KDL for one `ThemeSpec` — pure (unit-tested). The chrome
/// slots derive from the content slots: emphases follow the upstream asset
/// themes' hue pattern (0≈warn/orange · 1≈info/cyan · 2≈success/green ·
/// 3≈attention/pink), ribbons use the accent fill the pui's selected rows use,
/// frames use the pane-border slots.
pub fn theme_kdl(spec: &ThemeSpec) -> String {
    let t = spec;
    let std_emph = [t.warn, t.sky, t.sage, t.human];
    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push('\n');
    out.push_str("themes {\n");
    out.push_str(&format!("    {} {{\n", t.name));
    component(&mut out, "text_unselected", t.ink, t.panel, std_emph);
    component(&mut out, "text_selected", t.ink, t.panel_active, std_emph);
    component(
        &mut out,
        "ribbon_selected",
        t.on_accent,
        t.accent_hot,
        [t.danger, t.warn, t.human, t.sky],
    );
    component(
        &mut out,
        "ribbon_unselected",
        t.panel,
        t.muted,
        [t.danger, t.ink, t.sky, t.human],
    );
    component(&mut out, "table_title", t.accent, t.panel, std_emph);
    component(
        &mut out,
        "table_cell_selected",
        t.ink,
        t.panel_active,
        std_emph,
    );
    component(&mut out, "table_cell_unselected", t.ink, t.panel, std_emph);
    component(&mut out, "list_selected", t.ink, t.panel_active, std_emph);
    component(&mut out, "list_unselected", t.ink, t.panel, std_emph);
    component(
        &mut out,
        "frame_selected",
        t.border_active,
        t.panel,
        [t.warn, t.sky, t.human, t.panel],
    );
    component(
        &mut out,
        "frame_highlight",
        t.accent,
        t.panel,
        [t.accent_hot, t.accent, t.accent, t.accent],
    );
    component(
        &mut out,
        "exit_code_success",
        t.sage,
        t.panel,
        [t.sky, t.panel, t.human, t.border],
    );
    component(
        &mut out,
        "exit_code_error",
        t.danger,
        t.panel,
        [t.warn, t.panel, t.panel, t.panel],
    );
    // multiplayer_user_colors is positional (player_1..player_10).
    out.push_str("        multiplayer_user_colors {\n");
    let players = [
        t.human,
        t.sky,
        t.sage,
        t.warn,
        t.accent,
        t.danger,
        t.accent_hot,
        t.muted,
        t.border_active,
        t.ink,
    ];
    for (i, c) in players.iter().enumerate() {
        out.push_str(&format!("            player_{} {}\n", i + 1, fmt_color(*c)));
    }
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

// ─── Additive install ────────────────────────────────────────────────────────

/// Write one `<name>.kdl` per registered theme into `themes_dir` (created if
/// missing). Additive: a file that exists WITHOUT our generated header is a
/// user's own theme — skipped, never clobbered; our own files regenerate so
/// they track `ThemeSpec` changes.
pub fn install_themes(themes_dir: &Path) -> io::Result<(Vec<String>, Vec<String>)> {
    fs::create_dir_all(themes_dir)?;
    let mut installed = Vec::new();
    let mut skipped = Vec::new();
    for spec in THEMES {
        let path = themes_dir.join(format!("{}.kdl", spec.name));
        if path.exists() {
            let head = fs::read_to_string(&path).unwrap_or_default();
            if !head.starts_with(GENERATED_HEADER) {
                skipped.push(spec.name.to_string());
                continue;
            }
        }
        fs::write(&path, theme_kdl(spec))?;
        installed.push(spec.name.to_string());
    }
    Ok((installed, skipped))
}

// ─── The managed config.kdl line ─────────────────────────────────────────────

/// Is this line an ACTIVE (uncommented) top-level `theme "<name>"` statement?
/// Returns the selected name. (`theme_dir`, `theme_dark`… don't match; a
/// commented `// theme "x"` doesn't either.)
fn active_theme_line(line: &str) -> Option<String> {
    let t = line.trim_start();
    let rest = t.strip_prefix("theme")?;
    let rest = rest.trim_start();
    let rest = rest.strip_prefix('"')?;
    let (name, _) = rest.split_once('"')?;
    Some(name.to_string())
}

/// Point the single pui-managed `theme "<name>"` line at `name`:
/// - our marked line exists → rewrite it in place;
/// - the user has their OWN active `theme` line (no marker) → respect it,
///   change nothing, report the name (D-003 risk rule);
/// - neither → append the marked line.
///
/// The first managed write snapshots `config.kdl` to `config.kdl.pui-bak`
/// (once — the backup is the pre-pui state, never overwritten).
pub fn set_config_theme_line(config_path: &Path, name: &str) -> io::Result<ConfigOutcome> {
    let content = if config_path.exists() {
        fs::read_to_string(config_path)?
    } else {
        String::new()
    };

    let managed_line = format!("theme \"{name}\" {MANAGED_MARKER}");
    let mut lines: Vec<String> = content.lines().map(|l| l.to_string()).collect();
    let mut replaced = false;

    for line in lines.iter_mut() {
        if line.contains(MANAGED_MARKER) {
            *line = managed_line.clone();
            replaced = true;
            break;
        }
    }
    if !replaced {
        if let Some(user_theme) = lines.iter().find_map(|l| active_theme_line(l)) {
            return Ok(ConfigOutcome::RespectedUser(user_theme));
        }
    }

    // First managed write: back up the user's pre-pui config once.
    let backup = config_path.with_extension("kdl.pui-bak");
    if config_path.exists() && !backup.exists() {
        fs::copy(config_path, &backup)?;
    }

    if !replaced {
        lines.push(String::new());
        lines.push(
            "// pui :theme keeps the line below in sync with the workbench theme.".to_string(),
        );
        lines.push(managed_line);
    }
    let mut out = lines.join("\n");
    out.push('\n');
    fs::write(config_path, out)?;
    Ok(ConfigOutcome::Set)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::theme::{theme_by_name, HONEYCOMB};

    #[test]
    fn kdl_has_every_component_block_and_balances() {
        for spec in THEMES {
            let kdl = theme_kdl(spec);
            assert!(kdl.starts_with(GENERATED_HEADER));
            assert!(kdl.contains(&format!("    {} {{", spec.name)));
            for block in [
                "text_unselected",
                "text_selected",
                "ribbon_selected",
                "ribbon_unselected",
                "table_title",
                "table_cell_selected",
                "table_cell_unselected",
                "list_selected",
                "list_unselected",
                "frame_selected",
                "frame_highlight",
                "exit_code_success",
                "exit_code_error",
                "multiplayer_user_colors",
            ] {
                assert!(
                    kdl.contains(&format!("{block} {{")),
                    "{} missing {block}",
                    spec.name
                );
            }
            for p in 1..=10 {
                assert!(kdl.contains(&format!("player_{p} ")));
            }
            assert_eq!(
                kdl.matches('{').count(),
                kdl.matches('}').count(),
                "unbalanced braces in {}",
                spec.name
            );
        }
    }

    #[test]
    fn kdl_emits_rgb_triplets_from_the_spec() {
        let kdl = theme_kdl(&HONEYCOMB);
        // honeycomb ink = 244 235 212 (theme.rs) — the text base.
        assert!(kdl.contains("base 244 235 212"));
        // Named-ANSI slots map through the standard palette (papercusp-dark's
        // on_accent is Color::Black → "0 0 0").
        let dark = theme_by_name("papercusp-dark").unwrap();
        let kdl = theme_kdl(dark);
        assert!(kdl.contains("base 0 0 0") || kdl.contains("background 0 0 0"));
    }

    #[test]
    fn install_is_additive_and_regenerates_own_files() {
        let dir = tempfile::tempdir().unwrap();
        let themes = dir.path().join("themes");

        // A user's own file with a registry-colliding name is never clobbered.
        std::fs::create_dir_all(&themes).unwrap();
        std::fs::write(themes.join("honeycomb.kdl"), "themes { honeycomb { } }\n").unwrap();

        let (installed, skipped) = install_themes(&themes).unwrap();
        assert!(skipped.contains(&"honeycomb".to_string()));
        assert!(installed.contains(&"frost".to_string()));
        assert_eq!(
            std::fs::read_to_string(themes.join("honeycomb.kdl")).unwrap(),
            "themes { honeycomb { } }\n",
            "user content clobbered"
        );

        // Our own generated files regenerate freely.
        let (installed2, _) = install_themes(&themes).unwrap();
        assert!(installed2.contains(&"frost".to_string()));
        assert!(std::fs::read_to_string(themes.join("frost.kdl"))
            .unwrap()
            .starts_with(GENERATED_HEADER));
    }

    #[test]
    fn managed_line_appends_rewrites_and_backs_up_once() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join("config.kdl");
        std::fs::write(&cfg, "// keybinds etc\n// theme \"dracula\"\n").unwrap();

        // First write: appends the marked line + backs up the pre-pui config.
        assert_eq!(
            set_config_theme_line(&cfg, "frost").unwrap(),
            ConfigOutcome::Set
        );
        let after = std::fs::read_to_string(&cfg).unwrap();
        assert!(after.contains(&format!("theme \"frost\" {MANAGED_MARKER}")));
        assert!(after.contains("// keybinds etc"), "user content preserved");
        let bak = std::fs::read_to_string(dir.path().join("config.kdl.pui-bak")).unwrap();
        assert!(!bak.contains(MANAGED_MARKER), "backup is the pre-pui state");

        // Second write: rewrites the ONE managed line in place (no growth),
        // and the backup still holds the original state.
        assert_eq!(
            set_config_theme_line(&cfg, "honeycomb").unwrap(),
            ConfigOutcome::Set
        );
        let after2 = std::fs::read_to_string(&cfg).unwrap();
        assert_eq!(
            after2.matches("theme \"").count(),
            2,
            "commented example + managed line"
        );
        assert!(after2.contains(&format!("theme \"honeycomb\" {MANAGED_MARKER}")));
        assert!(!after2.contains("theme \"frost\""));
        assert!(
            !std::fs::read_to_string(dir.path().join("config.kdl.pui-bak"))
                .unwrap()
                .contains(MANAGED_MARKER)
        );
    }

    #[test]
    fn user_owned_theme_line_is_respected() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join("config.kdl");
        std::fs::write(&cfg, "theme \"gruvbox\"\n").unwrap();
        let before = std::fs::read_to_string(&cfg).unwrap();

        assert_eq!(
            set_config_theme_line(&cfg, "frost").unwrap(),
            ConfigOutcome::RespectedUser("gruvbox".into())
        );
        assert_eq!(std::fs::read_to_string(&cfg).unwrap(), before, "untouched");
        assert!(
            !dir.path().join("config.kdl.pui-bak").exists(),
            "no backup on a no-op"
        );
    }

    #[test]
    fn commented_and_prefixed_theme_lines_do_not_match() {
        assert_eq!(active_theme_line("// theme \"dracula\""), None);
        assert_eq!(active_theme_line("theme_dir \"/tmp\""), None);
        assert_eq!(active_theme_line("  theme \"nord\"  "), Some("nord".into()));
        // The managed line itself parses as a theme line (the marker check
        // runs first in set_config_theme_line).
        assert_eq!(
            active_theme_line(&format!("theme \"frost\" {MANAGED_MARKER}")),
            Some("frost".into())
        );
    }

    #[test]
    fn sync_in_composes_end_to_end() {
        let dir = tempfile::tempdir().unwrap();
        let out = sync_in(dir.path(), "honeycomb").unwrap();
        assert!(out.installed.contains(&"honeycomb".to_string()));
        assert_eq!(out.config, ConfigOutcome::Set);
        assert!(dir.path().join("themes/honeycomb.kdl").exists());
        assert!(std::fs::read_to_string(dir.path().join("config.kdl"))
            .unwrap()
            .contains(&format!("theme \"honeycomb\" {MANAGED_MARKER}")));
    }
}
