#!/usr/bin/env node
/**
 * check-prompt-projections.mjs — exact-byte guard for committed generated su.md
 * projections (EI-21618443971639284).
 *
 * The base su persona is authored in libs/papercusp/packages/harness, while the
 * operator and packaged desktop paths contain generated copies. A stale copy is
 * easy to miss because it is build output, but a consumer that reads it silently
 * receives an older persona. Compare bytes, not text lines or mtimes: line-based
 * probes can miss hard-wrapped policy and timestamps do not prove provenance.
 *
 *   node scripts/check-prompt-projections.mjs
 *   node scripts/check-prompt-projections.mjs --root /path/to/repo
 *   node scripts/check-prompt-projections.mjs --write
 *
 * The --root override exists only for the falsifiability tests. The normal guard
 * always resolves the repository root from this script's own location.
 */
import { createHash, randomUUID } from 'node:crypto';
import { mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isCliEntry } from '@papercusp/operator-core/lib/util/cli-entry';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The single authored base persona that owns the generated bytes. */
export const CANONICAL_PROMPT_PATH =
  'libs/papercusp/packages/harness/blueprints/base/prompts/su.md';

/**
 * Committed generated projections that must match the canonical source.
 *
 * The desktop primary sidecar under src-tauri/sidecar is intentionally not
 * required here: it is ignored build output and is absent in clean checkpoint
 * trees. The same now holds for apps/operator/dist-sidecar/ — it was untracked
 * and gitignored on 2026-09-02 (WI-2141120), so its su.md projection exists
 * only in a tree that has run the bundle build and is absent in the
 * green-checkpoint checkout; requiring it there reads as 'missing-projection'
 * on every candidate. The desktop staging projection is tracked and is the
 * durable artifact.
 */
export const GENERATED_PROMPT_PATHS = Object.freeze([
  'papercusp-desktop/src-tauri/env-sidecars/staging/harness/blueprints/base/prompts/su.md',
]);

/** Papercusp's authored pot-specific SU override and its tracked desktop copy. */
export const INSTANCE_PROMPT_SOURCE_PATH =
  'apps/operator/prompts/pot-instances/papercup-pot.su.md';
export const INSTANCE_PROMPT_PROJECTION_PATHS = Object.freeze([
  'papercusp-desktop/src-tauri/env-sidecars/staging/prompts/pot-instances/papercup-pot.su.md',
]);

/** Every authored source whose tracked desktop projection must stay byte-identical. */
export const PROMPT_PROJECTION_GROUPS = Object.freeze([
  Object.freeze({
    sourcePath: CANONICAL_PROMPT_PATH,
    projectionPaths: GENERATED_PROMPT_PATHS,
  }),
  Object.freeze({
    sourcePath: INSTANCE_PROMPT_SOURCE_PATH,
    projectionPaths: INSTANCE_PROMPT_PROJECTION_PATHS,
  }),
]);

export const PROMPT_PROJECTIONS_MARKER = '__PROMPT_PROJECTIONS__';

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function readBytes(path, read) {
  try {
    const value = read(path);
    return {
      bytes: Buffer.isBuffer(value) ? value : Buffer.from(value),
      errorCode: null,
    };
  } catch (error) {
    return {
      bytes: null,
      errorCode:
        error && typeof error === 'object' && 'code' in error
          ? String(error.code)
          : 'READ_FAILED',
    };
  }
}

function fileSummary(readPath, read, displayPath = readPath) {
  const result = readBytes(readPath, read);
  return {
    path: displayPath,
    exists: result.bytes !== null,
    bytes: result.bytes === null ? null : result.bytes.length,
    sha256: result.bytes === null ? null : sha256(result.bytes),
    errorCode: result.errorCode,
    _bytes: result.bytes,
  };
}

/**
 * Compare the canonical prompt with every committed generated projection.
 *
 * The read function is injectable so tests can prove the detector is
 * falsifiable without mutating this shared checkout. The returned summaries
 * intentionally expose hashes and byte counts, never prompt contents.
 */
export function comparePromptProjections({
  root = REPO_ROOT,
  sourcePath = CANONICAL_PROMPT_PATH,
  projectionPaths = GENERATED_PROMPT_PATHS,
  read = readFileSync,
} = {}) {
  const source = fileSummary(resolve(root, sourcePath), read, sourcePath);
  const projections = projectionPaths.map((path) =>
    fileSummary(resolve(root, path), read, path),
  );
  const mismatches = [];

  if (!source.exists) {
    mismatches.push({
      path: sourcePath,
      reason: source.errorCode === 'ENOENT' ? 'missing-source' : 'unreadable-source',
    });
  } else {
    for (const projection of projections) {
      if (!projection.exists) {
        mismatches.push({
          path: projection.path,
          reason: projection.errorCode === 'ENOENT' ? 'missing-projection' : 'unreadable-projection',
        });
      } else if (projection.sha256 !== source.sha256) {
        mismatches.push({ path: projection.path, reason: 'content-differs' });
      }
    }
  }

  const cleanSource = {
    path: source.path,
    exists: source.exists,
    bytes: source.bytes,
    sha256: source.sha256,
    errorCode: source.errorCode,
  };
  const cleanProjections = projections.map(({ _bytes, ...projection }) => projection);
  return {
    ok: mismatches.length === 0 && source.exists,
    source: cleanSource,
    projections: cleanProjections,
    mismatches,
  };
}

/** Compare every maintained source/projection group used by the CLI guard. */
export function compareAllPromptProjections({
  root = REPO_ROOT,
  groups = PROMPT_PROJECTION_GROUPS,
  read = readFileSync,
} = {}) {
  const results = groups.map(({ sourcePath, projectionPaths }) =>
    comparePromptProjections({ root, sourcePath, projectionPaths, read }),
  );
  return {
    ok: results.every((result) => result.ok),
    groups: results,
    mismatches: results.flatMap((result) =>
      result.mismatches.map((mismatch) => ({
        sourcePath: result.source.path,
        ...mismatch,
      })),
    ),
  };
}

/**
 * Refresh stale tracked projections with an atomic same-directory rename.
 *
 * Read every source before writing anything so one missing source cannot leave
 * a partially refreshed projection set. Already-current targets are untouched.
 */
export function writePromptProjections({
  root = REPO_ROOT,
  groups = PROMPT_PROJECTION_GROUPS,
  read = readFileSync,
  write = writeFileSync,
  rename = renameSync,
  unlink = unlinkSync,
  mkdir = mkdirSync,
} = {}) {
  const prepared = groups.map(({ sourcePath, projectionPaths }) => {
    const source = readBytes(resolve(root, sourcePath), read);
    if (!source.bytes) {
      throw new Error(
        `${sourcePath}: ${source.errorCode === 'ENOENT' ? 'missing-source' : 'unreadable-source'}`,
      );
    }
    return { projectionPaths, bytes: source.bytes };
  });

  const written = [];
  for (const { projectionPaths, bytes } of prepared) {
    for (const projectionPath of projectionPaths) {
      const target = resolve(root, projectionPath);
      const current = readBytes(target, read);
      if (current.bytes?.equals(bytes)) continue;

      const targetDir = dirname(target);
      mkdir(targetDir, { recursive: true });
      const temporary = resolve(
        targetDir,
        `.${basename(target)}.prompt-projection-${process.pid}-${randomUUID()}.tmp`,
      );
      try {
        write(temporary, bytes, { flag: 'wx' });
        rename(temporary, target);
      } catch (error) {
        try {
          unlink(temporary);
        } catch {
          // The rename may already have consumed the temporary path.
        }
        throw error;
      }
      written.push(projectionPath);
    }
  }
  return written;
}

function rootFromArgs() {
  const index = process.argv.indexOf('--root');
  if (index === -1) return REPO_ROOT;
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) {
    console.error('check-prompt-projections: --root requires a directory');
    process.exitCode = 2;
    return null;
  }
  return resolve(value);
}

function main() {
  const root = rootFromArgs();
  if (!root) return;
  let written = [];
  if (process.argv.includes('--write')) {
    try {
      written = writePromptProjections({ root });
    } catch (error) {
      console.error(
        'check-prompt-projections: refused to write: ' +
          (error instanceof Error ? error.message : String(error)),
      );
      process.exitCode = 2;
      return;
    }
  }
  const result = compareAllPromptProjections({ root });
  console.log(PROMPT_PROJECTIONS_MARKER + ' ' + JSON.stringify({ ...result, written }));
  if (result.ok) {
    const projectionCount = result.groups.reduce(
      (count, group) => count + group.projections.length,
      0,
    );
    console.error(
      '✓ check-prompt-projections: ' +
        result.groups.length +
        ' authored source(s) match ' +
        projectionCount +
        ' generated projection(s)' +
        (written.length > 0 ? ` (${written.length} refreshed)` : ''),
    );
    return;
  }

  console.error(
    '✖ check-prompt-projections: generated su.md projection drift (' +
      result.mismatches.length +
      ' mismatch(es))',
  );
  for (const mismatch of result.mismatches) {
    console.error(
      '  - ' + mismatch.path + ': ' + mismatch.reason + ' (source ' + mismatch.sourcePath + ')',
    );
  }
  console.error(
    '  Regenerate tracked desktop prompt projections with ' +
      '`npm --prefix packages/operator-core run gen:prompt-projections`.',
  );
  process.exitCode = 1;
}

if (isCliEntry(import.meta.url)) main();
