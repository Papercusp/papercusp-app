#!/usr/bin/env node
/**
 * Fail-loud source guard for machine-authored turns sent through the managed CLI
 * transport. The existing unenrolled-spawn/import checks cover process roots and
 * detached imports; neither sees a new prompt-injection call site.
 *
 *   node scripts/check-no-unenrolled-injector.mjs
 *   node scripts/check-no-unenrolled-injector.mjs --list  # measured call-site census
 *
 * A prompt payload passes only when its data expression resolves to the shared
 * turn-enrollment API (or to a reviewed wrapper). A same-file import or a tag call
 * on an unrelated string is not evidence. Exact allowlist entries are reserved for
 * reviewed owner-authored pass-throughs and carry a reason.
 */
import { readFileSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { describeUnscanned, listFilesIncludingUntracked } from './lib/tracked-files.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const require_ = createRequire(import.meta.url);
let tsCache = null;
function ts() {
  if (!tsCache) tsCache = require_('typescript');
  return tsCache;
}

const SOURCE_RE = /\.(?:[cm]?[jt]sx?)$/i;
const TEST_RE = /\.(?:test|spec)\.[cm]?[jt]sx?$/i;
const DECLARATION_RE = /\.d\.[cm]?ts$/i;
const EXCLUDED_DIRS = [
  '_retired/',
  'node_modules/',
  'dist/',
  'build/',
  'coverage/',
  'target/',
  // Test-only support files can use ordinary .ts names without `.test.ts`.
  'packages/operator-core/test/',
  // Generated by apps/operator/bin/bundle-host.sh from canonical source files.
  'papercusp-desktop/src-tauri/env-sidecars/',
];
const SOURCE_HINT = /\b(?:injectIntoHost|injectIntoHostWithConfirmation|injectTurn|injectPsuHost|injectPsuHostWithConfirmation)\b/;
const TRANSPORT_NAMES = new Set([
  'injectIntoHost',
  'injectIntoHostWithConfirmation',
  'injectTurn',
]);
// These are dependency-injected aliases of the transport API. They are considered
// only in a file that also imports or names the canonical transport.
const TRANSPORT_ALIASES = new Set([
  'inject',
  'injectPsuHost',
  'injectPsuHostWithConfirmation',
  'confirming',
  'defaultInjectIntoHost',
]);
const TAG_HELPERS = new Set([
  'tagTurn',
  'tagTurnForInjection',
  'tagWakeText',
  'tagWatchdogContinuation',
  'taggedHealedWakeText',
  'recoveryFirstPrompt',
]);
const PROMPT_MODES = new Set(['turn', 'carry-respawn', 'reset']);

/** Reviewed owner-authored pass-throughs; keys are seeded from a --list census. */
export const ALLOWLIST = new Map([
  [
    'packages/operator-core/lib/su-session-claude-adapter.ts::ownerTurn::injectIntoHostWithConfirmation::content::1',
    'Authenticated owner input passes through unchanged so it remains owner-authored.',
  ],
  [
    'packages/operator-core/lib/su-session-codex-adapter.ts::ownerTurn::injectIntoHostWithConfirmation::content::1',
    'Authenticated owner input passes through unchanged so it remains owner-authored.',
  ],
  [
    'packages/operator-core/lib/su-session-omp-adapter.ts::ownerTurn::injectIntoHostWithConfirmation::content::1',
    'Authenticated owner input passes through unchanged so it remains owner-authored.',
  ],
]);

function isFunctionLike(t, node) {
  return (
    t.isFunctionDeclaration(node) ||
    t.isFunctionExpression(node) ||
    t.isArrowFunction(node) ||
    t.isMethodDeclaration(node) ||
    t.isConstructorDeclaration(node) ||
    t.isGetAccessorDeclaration(node) ||
    t.isSetAccessorDeclaration(node)
  );
}

function unwrap(t, node) {
  let current = node;
  while (current) {
    if (
      t.isAwaitExpression(current) ||
      t.isParenthesizedExpression(current) ||
      t.isAsExpression(current) ||
      t.isTypeAssertionExpression(current) ||
      t.isNonNullExpression(current) ||
      t.isSatisfiesExpression(current)
    ) {
      current = current.expression;
    } else {
      break;
    }
  }
  return current;
}

function calleeName(t, expression) {
  const node = unwrap(t, expression);
  if (t.isIdentifier(node)) return node.text;
  if (t.isPropertyAccessExpression(node)) return node.name.text;
  if (t.isElementAccessExpression(node) && node.argumentExpression && t.isStringLiteral(node.argumentExpression)) {
    return node.argumentExpression.text;
  }
  return null;
}

function enclosingFunction(t, node) {
  for (let current = node; current; current = current.parent) {
    if (isFunctionLike(t, current)) return current;
  }
  return null;
}

function functionName(t, fn) {
  if (!fn) return '<module>';
  if (fn.name && (t.isIdentifier(fn.name) || t.isStringLiteral(fn.name))) return fn.name.text;
  const parent = fn.parent;
  if (parent && t.isVariableDeclaration(parent) && t.isIdentifier(parent.name)) return parent.name.text;
  if (parent && (t.isPropertyAssignment(parent) || t.isPropertyDeclaration(parent)) && parent.name) {
    return t.isIdentifier(parent.name) || t.isStringLiteral(parent.name) ? parent.name.text : '<computed-property>';
  }
  return `<anonymous@${fn.getSourceFile().getLineAndCharacterOfPosition(fn.getStart()).line + 1}>`;
}

function importedTransportNames(t, sourceFile) {
  const names = new Set(TRANSPORT_NAMES);
  function visit(node) {
    if (t.isImportDeclaration(node) && node.importClause?.namedBindings && t.isNamedImports(node.importClause.namedBindings)) {
      for (const element of node.importClause.namedBindings.elements) {
        const imported = element.propertyName?.text ?? element.name.text;
        if (TRANSPORT_NAMES.has(imported)) names.add(element.name.text);
      }
    }
    t.forEachChild(node, visit);
  }
  visit(sourceFile);
  return names;
}

function localDefinitions(t, name, callNode, sourceFile) {
  const scope = enclosingFunction(t, callNode) ?? sourceFile;
  const definitions = [];
  function visit(node) {
    if (node !== scope && isFunctionLike(t, node)) return;
    if (
      t.isVariableDeclaration(node) &&
      t.isIdentifier(node.name) &&
      node.name.text === name &&
      node.initializer &&
      t.isVariableDeclarationList(node.parent) &&
      (node.parent.flags & t.NodeFlags.Const) !== 0
    ) {
      // Only immutable bindings prove that the injected value is the tagged
      // value. Collecting every assignment made `let data = raw; try { data =
      // tag(raw) } catch {}` look enrolled even though the catch injects raw.
      // Mutable aliases stay unknown and must be made explicit by the caller.
      definitions.push(node.initializer);
    }
    t.forEachChild(node, visit);
  }
  visit(scope);
  return definitions;
}

function findObjectLiteral(t, node, callNode, sourceFile, seen = new Set()) {
  const current = unwrap(t, node);
  if (!current) return null;
  if (t.isObjectLiteralExpression(current)) return current;
  if (t.isIdentifier(current) && !seen.has(current.text)) {
    seen.add(current.text);
    for (const value of localDefinitions(t, current.text, callNode, sourceFile)) {
      const found = findObjectLiteral(t, value, callNode, sourceFile, seen);
      if (found) return found;
    }
  }
  return null;
}

function propertyValue(t, object, name) {
  if (!object) return null;
  for (const property of object.properties) {
    if (t.isShorthandPropertyAssignment(property)) {
      if (property.name.text === name) return property.name;
      continue;
    }
    if (!t.isPropertyAssignment(property)) continue;
    const key = property.name;
    const text = t.isIdentifier(key) || t.isStringLiteral(key) ? key.text : null;
    if (text === name) return property.initializer;
  }
  return null;
}

function functionHasLocalBinding(t, fn, name) {
  const body = fn.body;
  if (!body) return false;
  let found = false;
  function visit(node) {
    if (node !== body && isFunctionLike(t, node)) return;
    if (t.isVariableDeclaration(node) && t.isIdentifier(node.name) && node.name.text === name) {
      found = true;
      return;
    }
    t.forEachChild(node, visit);
  }
  visit(body);
  return found;
}

function isEnrolledParameter(t, name, callNode) {
  for (let current = callNode; current; current = current.parent) {
    if (!isFunctionLike(t, current)) continue;
    // Stop at the nearest lexical binding. A same-named raw local or parameter
    // must not inherit an outer function's enrollment brand.
    if (functionHasLocalBinding(t, current, name)) return false;
    const parameter = current.parameters?.find((entry) => t.isIdentifier(entry.name) && entry.name.text === name);
    if (!parameter) continue;
    if (!parameter.type || !t.isTypeReferenceNode(parameter.type)) return false;
    const typeName = parameter.type.typeName;
    // This brand marks text that crossed wake-executor's enrollment boundary.
    return t.isIdentifier(typeName) && typeName.text === 'EnrolledWakeText';
  }
  return false;
}

function containsTagHelper(t, node, callNode, sourceFile, seen = new Set()) {
  const current = unwrap(t, node);
  if (!current) return false;
  if (t.isCallExpression(current) && TAG_HELPERS.has(calleeName(t, current.expression))) return true;
  if (t.isIdentifier(current)) {
    if (isEnrolledParameter(t, current.text, callNode)) return true;
    const key = `${functionName(t, enclosingFunction(t, callNode))}:${current.text}`;
    if (seen.has(key)) return false;
    seen.add(key);
    const definitions = localDefinitions(t, current.text, callNode, sourceFile);
    if (definitions.some((definition) => containsTagHelper(t, definition, callNode, sourceFile, seen))) return true;
  }
  let found = false;
  t.forEachChild(current, (child) => {
    if (!found && containsTagHelper(t, child, callNode, sourceFile, seen)) found = true;
  });
  return found;
}

function promptMode(t, object, callee, optionsArg) {
  if (callee === 'injectTurn') return 'turn';
  const modeNode = propertyValue(t, object, 'mode');
  if (!modeNode) {
    // An unresolved options alias may still carry a prompt. Keep it in the
    // measured population and fail closed instead of silently skipping it.
    return (object && propertyValue(t, object, 'data')) || (!object && optionsArg) ? 'unknown' : null;
  }
  const mode = unwrap(t, modeNode);
  if (t.isStringLiteral(mode) || t.isNoSubstitutionTemplateLiteral(mode)) {
    return PROMPT_MODES.has(mode.text) ? mode.text : null;
  }
  // A dynamic mode can include a user turn or carry-respawn, so keep it visible.
  return 'dynamic';
}

function dataExpression(t, object, callNode, sourceFile, callee) {
  if (object) return propertyValue(t, object, 'data');
  if (callee === 'injectTurn') return callNode.arguments[1] ?? null;
  return null;
}

function isPtyTransportForwarder(t, callNode, name, sourceFile) {
  const argument = callNode.arguments[1];
  return (
    sourceFile.fileName === 'packages/operator-core/lib/events/await/psu-pty-discovery.ts' &&
    name === 'injectIntoHostWithConfirmation' &&
    functionName(t, enclosingFunction(t, callNode)) === 'injectIntoHost' &&
    argument &&
    t.isIdentifier(argument) &&
    argument.text === 'msg'
  );
}

/**
 * Enumerate managed prompt transport call sites in one source file. Enrollment is
 * tied to the transported `data` expression: helper use elsewhere in the function
 * cannot make an unrelated raw payload look enrolled.
 */
export function findTurnInjectionSites(source, fileName = 'source.ts') {
  const t = ts();
  const kind = fileName.endsWith('.tsx') ? t.ScriptKind.TSX : fileName.endsWith('.jsx') ? t.ScriptKind.JSX :
    fileName.endsWith('.mjs') || fileName.endsWith('.cjs') || fileName.endsWith('.js') ? t.ScriptKind.JS : t.ScriptKind.TS;
  const sourceFile = t.createSourceFile(fileName, source, t.ScriptTarget.Latest, true, kind);
  const importedNames = importedTransportNames(t, sourceFile);
  const hasTransportReference = SOURCE_HINT.test(source);
  const aliasNames = hasTransportReference ? TRANSPORT_ALIASES : new Set();
  const sites = [];
  const occurrences = new Map();

  function visit(node) {
    if (t.isCallExpression(node)) {
      const name = calleeName(t, node.expression);
      const isTransport = name && (importedNames.has(name) || aliasNames.has(name));
      // The PTY module owns the byte transport and forwards a caller-constructed
      // protocol message through this wrapper. Prompt origin is established by
      // the caller; this internal forwarding call does not author prompt text.
      if (isTransport && !isPtyTransportForwarder(t, node, name, sourceFile)) {
        const options = findObjectLiteral(t, node.arguments[1], node, sourceFile);
        const mode = promptMode(t, options, name, node.arguments[1]);
        if (mode) {
          const data = dataExpression(t, options, node, sourceFile, name);
          const line = sourceFile.getLineAndCharacterOfPosition(node.getStart()).line + 1;
          const ownerFunction = functionName(t, enclosingFunction(t, node));
          const dataText = data ? data.getText(sourceFile).replace(/\s+/g, ' ').trim() : '<missing-data>';
          const baseKey = `${fileName}::${ownerFunction}::${name}::${dataText}`;
          const ordinal = (occurrences.get(baseKey) ?? 0) + 1;
          occurrences.set(baseKey, ordinal);
          sites.push({
            file: fileName,
            line,
            functionName: ownerFunction,
            callee: name,
            mode,
            dataText,
            enrolled: containsTagHelper(t, data, node, sourceFile),
            key: `${baseKey}::${ordinal}`,
          });
        }
      }
    }
    t.forEachChild(node, visit);
  }
  visit(sourceFile);
  return sites;
}

export function isExcluded(file) {
  return (
    !SOURCE_RE.test(file) ||
    TEST_RE.test(file) ||
    DECLARATION_RE.test(file) ||
    EXCLUDED_DIRS.some((dir) => file.startsWith(dir) || file.includes(`/${dir}`))
  );
}

function readSource(file) {
  try {
    return readFileSync(resolve(ROOT, file), 'utf8');
  } catch {
    return null;
  }
}

function scanRealTree() {
  const { files, ...coverage } = listFilesIncludingUntracked(ROOT);
  const candidates = files.filter((file) => !isExcluded(file));
  const sites = [];
  let parsed = 0;
  for (const file of candidates) {
    const raw = readSource(file);
    if (raw === null || !SOURCE_HINT.test(raw)) continue;
    parsed += 1;
    sites.push(...findTurnInjectionSites(raw, file));
  }
  return { sites, coverage, parsed };
}

function main() {
  const listMode = process.argv.includes('--list');
  const { sites, coverage, parsed } = scanRealTree();
  const byKey = new Map(sites.map((site) => [site.key, site]));
  const untagged = sites.filter((site) => !site.enrolled);
  if (listMode) {
    console.log(`[no-unenrolled-injector] measured ${sites.length} prompt site(s) across ${parsed} source file(s)`);
    for (const site of [...sites].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)) {
      const reason = ALLOWLIST.get(site.key);
      const state = site.enrolled ? 'ENROLLED' : reason ? 'ALLOWLIST' : 'UNENROLLED';
      console.log(`  ${state} ${site.key} @${site.line} mode=${site.mode}${reason ? ` reason=${reason}` : ''}`);
    }
    const unscanned = describeUnscanned(coverage, ROOT);
    if (unscanned) console.log(unscanned);
    return;
  }

  const stale = [...ALLOWLIST.keys()].filter((key) => !byKey.has(key));
  const offenders = untagged.filter((site) => !ALLOWLIST.has(site.key));
  const unreasoned = [...ALLOWLIST].filter(([, reason]) => typeof reason !== 'string' || !reason.trim());
  if (stale.length || offenders.length || unreasoned.length) {
    console.error('[no-unenrolled-injector] FAIL — every machine-authored prompt must carry turn-provenance enrollment:');
    for (const site of offenders) console.error(`  ${site.file}:${site.line} ${site.functionName} → ${site.callee}(${site.dataText}) [${site.mode}]`);
    for (const key of stale) console.error(`  stale allowlist entry: ${key}`);
    for (const [key] of unreasoned) console.error(`  allowlist entry lacks a reason: ${key}`);
    console.error(
      '\nEnroll the exact payload with `tagTurnForInjection` (or a reviewed tagged-text wrapper). ' +
        'An owner-authored pass-through needs an exact ALLOWLIST entry with a reason. ' +
        'Use --list to inspect the measured call-site population; never seed exemptions from grep.',
    );
    process.exitCode = 1;
    return;
  }

  const allowlisted = untagged.filter((site) => ALLOWLIST.has(site.key));
  console.log(
    `[no-unenrolled-injector] OK — ${sites.length} prompt site(s), ${parsed} source file(s), ` +
      `${allowlisted.length} reasoned owner-authored exception(s)`,
  );
}

const invokedDirectly = (() => {
  try {
    return realpathSync(process.argv[1] ?? '') === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
})();
if (invokedDirectly) main();
